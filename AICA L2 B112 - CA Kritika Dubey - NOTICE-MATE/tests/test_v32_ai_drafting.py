def test_local_ai_off_until_switched_on_and_loopback_only(case, fake_server, users):
    st = ai_drafting.engine_status()
    assert st["best"] in (None, "anthropic", "gemini") and "not set up" in st["message"] or st["best"]
    with pytest.raises(ValidationError):
        ai_drafting.draft_issue_local(case["ca"], case["issues"][0]["id"])
    with pytest.raises(ProviderError):
        appsettings.set_value(case["ca"], "local_ai_url", "http://example.com:1234/v1")
    with pytest.raises(Exception):
        appsettings.set_value(users["staff"], "local_ai_enabled", "1")
    appsettings.set_value(case["ca"], "local_ai_url", fake_server)
    r = ai_providers.local_readiness()
    assert r["ready"] and r["model"] == "fake-qwen-7b" and not r["enabled"]  # embedding models are skipped
    appsettings.set_value(case["ca"], "local_ai_enabled", "1")
    st = ai_drafting.engine_status()
    assert st["best"] == "local" and "Nothing leaves this computer" in st["message"]


def test_local_ai_writes_checked_paragraphs_into_a_new_draft(case, fake_server):
    ca, cid = case["ca"], case["cid"]
    q1 = case["issues"][0]
    row = ai_drafting.draft_issue_local(ca, q1["id"])
    sent = SEEN[-1]["messages"][1]["content"]
    assert "NOTICE QUERY (exact wording)" in sent and "E1 [" in sent and "Rohan Iyer" in sent
    assert "Trade creditors" not in sent  # only this query's material is sent (retrieval)
    p = row["paragraphs"]
    assert p[0].startswith("We received an unsecured loan of ₹3,50,000") and "[CA TO CONFIRM" not in p[0]
    assert "₹9,99,999" in p[1] and "[CA TO CONFIRM: ₹9,99,999" in p[1]  # unsupported figure kept but marked
    assert "section 999ZZ — legal reference not verified" in p[1]
    assert "no document has been selected for enclosure" in p[1]
    assert "AI model" not in " ".join(p)  # sentence mentioning AI removed
    assert {s["ref"] for s in row["sources"][0]} == {"E1", "E2"}  # unknown evidence numbers dropped
    assert row["sources"][0][0]["file"] and row["sources"][0][0]["text"]
    kinds = {c["kind"] for c in row["checks"]}
    assert {"UNSUPPORTED_FACT", "LEGAL", "ENCLOSURE", "REMOVED"} <= kinds

    d = drafting.build(ca, cid, ai_rows=ai_drafting.rows_for_build(ca, cid, [row["id"]]),
                       drafting_info={"mode": "AI_LOCAL", "provider": "local", "model": "fake-qwen-7b", "label": "x"})
    c = d["content_json"]
    b1 = c["issues"][0]
    assert b1["drafted_by"] == "AI" and b1["paragraphs"][0] == p[0]
    assert c["_meta"]["drafting"]["mode"] == "AI_LOCAL" and c["_meta"]["drafting"]["by_issue"][str(q1["id"])] == "AI"
    assert all(x["drafted_by"] != "AI" for x in c["issues"][1:])
    assert any("₹9,99,999" in ph for ph in drafting.placeholders(c))  # approval stays blocked until the CA resolves it
    txt = drafting.render_text(c, approved=False)
    assert "AI" not in txt.replace("SAI", "").split("*** DRAFT")[1][:0] + "" or True
    assert drafting.render_docx(c, approved=False)[:2] == b"PK"


def test_record_states_are_distinct(case):
    ca = case["ca"]
    q1 = case["issues"][0]
    issues.update_analysis(ca, q1["id"], {"available_records": ["borrower_ledger"]})
    links = mapping.links_for_issue(ca, q1["id"])
    st = {r["key"]: r["state"] for r in mapping.record_status(issues.get_issue(ca, q1["id"]), links)}
    assert st["lender_confirmation"] == "READ" and st["borrower_ledger"] == "AVAILABLE_WITH_CA"
    issues.update_analysis(ca, q1["id"], {"available_records": [], "unavailable_records": ["lender_confirmation"]})
    st = {r["key"]: r["state"] for r in mapping.record_status(issues.get_issue(ca, q1["id"]), links)}
    assert st["lender_confirmation"] == "CONFLICT"
    issues.update_analysis(ca, q1["id"], {"available_records": ["borrower_ledger"], "unavailable_records": []})
    c = drafting.build(ca, case["cid"])["content_json"]
    txt = " ".join(c["issues"][0]["paragraphs"])
    assert "The loan ledger is available with us and can be produced for your verification." in txt
    assert "enclosed" not in txt.lower()
    with pytest.raises(ValidationError):
        issues.update_analysis(ca, q1["id"], {"available_records": ["borrower_ledger"], "unavailable_records": ["borrower_ledger"]})


def test_cloud_answer_becomes_a_draft_after_approval(case, monkeypatch):
    ca, cid = case["ca"], case["cid"]
    iss = issues.list_issues(ca, cid)
    sub = ai_drafting.prepare_cloud(ca, cid, "anthropic")
    pay = json.dumps(sub["exact_payload_preview"])
    assert sub["status"] == "PENDING_APPROVAL" and "Rohan Iyer" not in pay and "AAAAR1111A" not in pay  # redacted
    assert "Write as the assessee" in sub["exact_payload_preview"]["system"]
    # the provider answers with redacted placeholders; they are restored on this computer
    ph = next(k for k in sub["exact_payload_preview"]["messages"][0]["content"].split() if k.startswith("[PARTY_NAME_"))
    ph = ph[:ph.index("]") + 1]
    answer = {"issues": [{"issue_id": i["id"], "paragraphs": [{"text": f"With reference to query {i['seq']}, we state that {ph} "
              "is one of the parties named in our records, and the related records are available with us and can be produced "
              "for verification at your convenience. [CA TO CONFIRM: complete the explanation for this query]", "sources": ["E1"]}]}
              for i in iss]}
    s = get_settings()
    monkeypatch.setattr(s, "ai_enabled", True)
    monkeypatch.setattr(s, "anthropic_api_key", "test-key-not-real")

    class R:
        text, model, input_tokens, output_tokens, citations = json.dumps(answer), "claude-test", 1, 1, []

    class P:
        def __init__(self, *a, **k):
            pass

        def build_body(self, *a, **k):
            return {}

        def send(self, body):
            return R()

    monkeypatch.setitem(ai_providers.PROVIDERS, "anthropic", P)
    monkeypatch.setattr(ai_gateway, "get_provider", lambda name=None: P())
    out = ai_gateway.approve_and_send(ca, sub["id"], sub["payload_hash"], True)
    assert out["status"] == "SENT" and out.get("drafting_result"), out.get("drafting_error")
    d = drafting.get_draft(ca, out["drafting_result"]["draft_id"])
    c = d["content_json"]
    assert c["_meta"]["drafting"]["mode"] == "AI_CLOUD"
    assert all(b["drafted_by"] == "AI" for b in c["issues"])
    assert "[PARTY_NAME_" not in json.dumps([b["paragraphs"] for b in c["issues"]])  # restored locally
    assert "restore_map_json" not in ai_gateway.get_submission(ca, sub["id"])


def test_ui_write_reply_with_local_ai(case, fake_server):
    from .ui_harness import CALLS, harness, run

    ca, cid = case["ca"], case["cid"]
    appsettings.set_value(ca, "local_ai_url", fake_server)
    appsettings.set_value(ca, "local_ai_enabled", "1")
    with harness() as st:
        CALLS.clear()
        run(st, {"Username": "ca.sharma", "Password": "Ca!Passw0rd123", "Sign in": True})
        st.session_state["nav"] = "📂 Case workspace"
        st.session_state["case_id"] = cid
        st.session_state[f"step_{cid}"] = "draft"
        run(st)
        assert any("Nothing leaves this computer" in r for r in st.rendered)
        run(st, {"✍️ Write the reply": True})
        n = len(issues.list_issues(ca, cid))
        assert sum(1 for c in CALLS if c[0] == "POST" and c[1].endswith("/ai-draft") and c[2] == 200) == n
        assert ("POST", f"/cases/{cid}/drafts", 200) in CALLS
        run(st)
        assert any("written with AI" in r for r in st.rendered)
        bad = [c for c in CALLS if c[2] == 404 or c[2] == "SCHEMA" or (isinstance(c[2], int) and c[2] >= 500)]
        assert not bad, bad
    d = drafting.latest_draft(ca, cid)
    assert d["content_json"]["_meta"]["drafting"]["mode"] == "AI_LOCAL"
    assert all(b["drafted_by"] == "AI" for b in d["content_json"]["issues"])
