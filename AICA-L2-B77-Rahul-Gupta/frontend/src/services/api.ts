/** API client — all requests go to the FastAPI backend (never to the AI provider).
 *
 * Two build-time modes:
 *  - live (default): fetch against VITE_API_URL (or the Vite dev proxy).
 *  - static demo (VITE_STATIC_DEMO=true, used for GitHub Pages): GET requests are
 *    served from a bundled snapshot of the seeded engine data and simulations run
 *    through a display-only TS mirror of the Python engine. Mutating actions that
 *    genuinely need the backend fail with a friendly explanation.
 */

const API_BASE: string = import.meta.env.VITE_API_URL ?? "";
export const IS_STATIC_DEMO: boolean = import.meta.env.VITE_STATIC_DEMO === "true";

class ApiError extends Error {
  status: number;
  constructor(status: number, message: string) {
    super(message);
    this.status = status;
  }
}

async function request<T>(path: string, options: RequestInit = {}): Promise<T> {
  if (IS_STATIC_DEMO) {
    const { staticRequest } = await import("../demo/staticApi");
    return staticRequest<T>(path, options);
  }
  const res = await fetch(`${API_BASE}${path}`, {
    headers: options.body instanceof FormData ? {} : { "Content-Type": "application/json" },
    ...options,
  });
  if (!res.ok) {
    let detail = res.statusText;
    try {
      const body = await res.json();
      detail = body.detail || JSON.stringify(body);
    } catch {
      /* ignore */
    }
    throw new ApiError(res.status, detail);
  }
  return res.json();
}

export const api = {
  get: <T>(path: string) => request<T>(path),
  post: <T>(path: string, body?: unknown) =>
    request<T>(path, { method: "POST", body: body === undefined ? undefined : JSON.stringify(body) }),
  put: <T>(path: string, body: unknown) =>
    request<T>(path, { method: "PUT", body: JSON.stringify(body) }),
  upload: <T>(path: string, form: FormData) =>
    request<T>(path, { method: "POST", body: form }),
};

export { ApiError };

/** Where a generated report can be downloaded from. In the static Pages build the
 *  bundled sample report (generated by the real engine) is served instead. */
/** Fetch a generated report and save it, without needing a popup.
 *
 *  Generating a report takes many seconds, so `window.open` called after
 *  awaiting it runs long outside the user-gesture window and browsers block it
 *  silently — the button appears to do nothing at all. Fetching the bytes and
 *  clicking a synthetic anchor is not gesture-bound, and gives the file a real
 *  name instead of dumping it in a tab.
 */
export async function downloadReport(
  reportId: string, preferPdf: boolean, title?: string,
): Promise<void> {
  const url = reportDownloadUrl(reportId, preferPdf);
  const res = await fetch(url);
  if (!res.ok) {
    throw new ApiError(res.status, `Could not download the report (${res.status})`);
  }
  const blob = await res.blob();
  const href = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = href;
  anchor.download = `${(title || "valuation-report").replace(/[/\\?%*:|"<>]/g, "-")}`
    + `.${preferPdf ? "pdf" : "html"}`;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  // revoke late: Safari reads the blob asynchronously after the click
  setTimeout(() => URL.revokeObjectURL(href), 10_000);
}

export function reportDownloadUrl(reportId: string, preferPdf: boolean): string {
  if (IS_STATIC_DEMO) {
    return `${import.meta.env.BASE_URL}demo/sample-report.${preferPdf ? "pdf" : "html"}`;
  }
  return `${API_BASE}/api/reports/${reportId}/download?format=${preferPdf ? "pdf" : "html"}`;
}

/* ---------- formatting helpers (display only; engine owns the math) ---------- */

const CR = 1e7;

export function fmtCr(v: number | null | undefined, decimals = 2): string {
  if (v === null || v === undefined || Number.isNaN(v)) return "—";
  return `₹ ${(v / CR).toLocaleString("en-IN", {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  })} Cr`;
}

export function fmtCrPlain(v: number | null | undefined, decimals = 2): string {
  if (v === null || v === undefined || Number.isNaN(v)) return "—";
  return (v / CR).toLocaleString("en-IN", {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  });
}

export function fmtPct(v: number | null | undefined, decimals = 1, signed = false): string {
  if (v === null || v === undefined || Number.isNaN(v)) return "—";
  const s = (v * 100).toFixed(decimals);
  return `${signed && v > 0 ? "+" : ""}${s}%`;
}

export function fmtIndian(v: number | null | undefined): string {
  if (v === null || v === undefined) return "—";
  return v.toLocaleString("en-IN");
}

/** Guess an Indian fiscal-year label from a filename, or "" when unsure.
 *
 *  Only returns a label for a genuine consecutive-year pair. A naive
 *  `20\d{2}[-_ ]?(\d{2})` match turns "Statements_2024-2025.pdf" into "FY2024-20"
 *  and "ABC_20240331.pdf" into "FY2024-03" — invalid labels that the backend then
 *  stores as extra phantom periods alongside the real ones. Returning "" is safe:
 *  the extractor reads the period off the statement itself.
 */
export function fiscalYearFromFilename(name: string): string {
  const start = (y: number) => `FY${y}-${String((y + 1) % 100).padStart(2, "0")}`;

  // 2024-2025 / 2024_2025 — full four-digit pair
  const full = name.match(/(20\d{2})[-_/ ](20\d{2})(?!\d)/);
  if (full) {
    const [a, b] = [Number(full[1]), Number(full[2])];
    return b === a + 1 ? start(a) : "";
  }
  // FY2024-25 / 2024-25 — two-digit suffix, not part of a longer number
  const short = name.match(/(?<!\d)(20\d{2})[-_/ ](\d{2})(?!\d)/);
  if (short) {
    const a = Number(short[1]);
    return Number(short[2]) === (a + 1) % 100 ? start(a) : "";
  }
  return "";
}

export function fmtFileSize(bytes: number | null | undefined): string {
  if (!bytes) return "—";
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1048576) return `${(bytes / 1024).toFixed(0)} KB`;
  return `${(bytes / 1048576).toFixed(1)} MB`;
}

export function fmtDate(iso: string | null | undefined, withTime = false): string {
  if (!iso) return "—";
  const d = new Date(iso);
  const date = d.toLocaleDateString("en-IN", { year: "numeric", month: "short", day: "2-digit" });
  if (!withTime) return date;
  const time = d.toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit" });
  return `${date} ${time}`;
}
