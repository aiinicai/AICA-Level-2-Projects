def parse_tally_excel(file_path_or_bytes):
    """
    Parses Tally export Excel files.
    Tally exported Excel files usually have columns like:
    Ledger Name, Group/Parent, Opening Balance, Debit, Credit, Closing Balance
    or Opening Dr/Cr, Closing Dr/Cr.
    """
    # pandas read_excel requires a file path or file-like object, not raw bytes
    if isinstance(file_path_or_bytes, bytes):
        file_path_or_bytes = io.BytesIO(file_path_or_bytes)
    df = pd.read_excel(file_path_or_bytes, skiprows=0)
    # Clean header names
    df.columns = [str(c).strip() for c in df.columns]
    
    ledgers = []
    
    # Flexible column matching
    col_map = {}
    for col in df.columns:
        clow = col.lower()
        if 'ledger' in clow or 'particular' in clow or 'account' in clow or 'name' in clow:
            col_map['ledger'] = col
        elif 'group' in clow or 'parent' in clow or 'category' in clow:
            col_map['group'] = col
        elif 'open' in clow:
            col_map['opening'] = col
        elif 'debit' in clow or 'dr' in clow and 'close' not in clow and 'open' not in clow:
            col_map['debit'] = col
        elif 'credit' in clow or 'cr' in clow and 'close' not in clow and 'open' not in clow:
            col_map['credit'] = col
        elif 'close' in clow or 'closing' in clow:
            col_map['closing'] = col
        elif 'prior' in clow or 'comparative' in clow or 'py' in clow or 'prev' in clow:
            col_map['prior'] = col

    # Fallbacks if columns are positional
    if 'ledger' not in col_map and len(df.columns) > 0:
        col_map['ledger'] = df.columns[0]
    if 'group' not in col_map and len(df.columns) > 1:
        col_map['group'] = df.columns[1]

    current_group = "Primary"
    seen_names = set()   # deduplicate by ledger name
    for idx, row in df.iterrows():
        ledger_name = str(row.get(col_map.get('ledger', df.columns[0]), '')).strip()

        # Skip blank / header / total rows
        if not ledger_name or ledger_name.lower() in ['total', 'grand total', 'nan', 'none', 'particulars', 'ledger name']:
            continue
        # Skip group-separator rows generated by the Tally Converter (e.g. '— Capital Account —')
        if ledger_name.startswith('—') or ledger_name.startswith('---') or ledger_name.startswith('–'):
            continue
        # Deduplicate: keep first occurrence
        if ledger_name in seen_names:
            continue
        seen_names.add(ledger_name)
            
        group_name = str(row.get(col_map.get('group', ''), '')).strip()
        if not group_name or group_name.lower() == 'nan':
            # Check if this row is a group header in Tally single column export
            group_name = current_group
        else:
            current_group = group_name

        def safe_float(val):
            """Parse amount, returning signed float (Cr suffix → negative)."""
            if pd.isna(val) or val is None: return 0.0
            val_str = str(val).replace(',', '').strip()
            # Handle Tally Dr/Cr suffixes like "150000 Dr" or "50000 Cr"
            is_cr = 'cr' in val_str.lower()
            val_str = val_str.lower().replace('dr', '').replace('cr', '').strip()
            try:
                num = float(val_str)
                return -num if is_cr else num
            except:
                return 0.0

        def has_sign(key):
            """Return True if the cell for this key has an explicit Dr/Cr suffix."""
            col_name = col_map.get(key)
            if not col_name or col_name not in row:
                return False
            raw = str(row[col_name]).strip().lower()
            return raw.endswith('dr') or raw.endswith('cr')

        def safe_get(key):
            col_name = col_map.get(key)
            if not col_name or col_name not in row:
                return 0.0
            return safe_float(row[col_name])

        opening_val = safe_get('opening')
        debit_val   = abs(safe_get('debit'))
        credit_val  = abs(safe_get('credit'))
        prior_val   = safe_get('prior')

        # Determine closing balance with correct sign:
        #   • If the closing cell has an explicit Dr/Cr suffix → trust it directly.
        #   • Otherwise Tally exported a plain unsigned positive number.
        #     Use the fundamental double-entry formula:
        #       closing = opening(signed) + debit(abs) - credit(abs)
        #     This is always sign-correct because:
        #       - opening is signed negative for Cr-normal accounts
        #       - debit/credit are absolute transaction amounts
        if has_sign('closing'):
            closing_val = safe_get('closing')
        else:
            closing_val = opening_val + debit_val - credit_val

        ledgers.append({
            'ledger_name': ledger_name,
            'tally_group': group_name if group_name else 'Unassigned Group',
            'opening_dr': opening_val if opening_val > 0 else 0.0,
            'opening_cr': abs(opening_val) if opening_val < 0 else 0.0,
            'debit': debit_val,
            'credit': credit_val,
            'closing_dr': closing_val if closing_val > 0 else 0.0,
            'closing_cr': abs(closing_val) if closing_val < 0 else 0.0,
            'closing_net': closing_val,
            'prior_closing_net': prior_val
        })

    # ── Strip Tally group-summary rows ──────────────────────────────────────
    ALL_TALLY_GROUPS = {
        'capital account', 'reserves & surplus', 'current liabilities', 'duties & taxes',
        'provisions', 'bank od a/c', 'secured loans', 'unsecured loans',
        'loans (liability)', 'fixed assets', 'investments', 'current assets', 'bank accounts',
        'cash-in-hand', 'deposits (asset)', 'loans & advances (asset)',
        'stock-in-hand', 'sales accounts', 'purchase accounts', 'direct incomes',
        'indirect incomes', 'direct expenses', 'indirect expenses', 'branch / divisions',
        'misc. expenses (asset)', 'suspense a/c', 'primary'
    }
    child_groups = {l['tally_group'].lower() for l in ledgers}
    filtered_ledgers = []
    for l in ledgers:
        name_lower = l['ledger_name'].lower().strip()
        # Drop if it is a known group header or its name appears as a group of other ledgers
        if name_lower in child_groups:
            continue
        if name_lower in ALL_TALLY_GROUPS and name_lower == l['tally_group'].lower().strip():
            continue
        filtered_ledgers.append(l)

    return filtered_ledgers

