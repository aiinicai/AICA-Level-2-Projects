def parse_tally_xml(file_path_or_bytes):
    """
    Parses Tally XML exported file (<ENVELOPE><BODY><DATA><TALLYMESSAGE><LEDGER>...)
    """
    # ET.parse requires a file path or file-like object, not raw bytes
    if isinstance(file_path_or_bytes, bytes):
        file_path_or_bytes = io.BytesIO(file_path_or_bytes)
    tree = ET.parse(file_path_or_bytes)
    root = tree.getroot()
    
    ledgers = []
    # Find all LEDGER nodes
    for ledger in root.findall('.//LEDGER'):
        name = ledger.get('NAME') or ledger.findtext('LANGUAGENAME.LIST/NAME.LIST/NAME') or ledger.findtext('NAME')
        if not name:
            continue
        parent = ledger.findtext('PARENT') or 'Primary'
        opening = ledger.findtext('OPENINGBALANCE') or '0'
        closing = ledger.findtext('CLOSINGBALANCE') or '0'
        
        def parse_xml_num(val):
            if not val: return 0.0
            val = val.replace(',', '').strip()
            is_cr = val.endswith('Cr') or val.startswith('-')
            clean_val = val.replace('Dr', '').replace('Cr', '').strip()
            try:
                num = float(clean_val)
                return -num if is_cr else num
            except:
                return 0.0

        op_num = parse_xml_num(opening)
        cl_num = parse_xml_num(closing)

        ledgers.append({
            'ledger_name': name,
            'tally_group': parent,
            'opening_dr': op_num if op_num > 0 else 0.0,
            'opening_cr': abs(op_num) if op_num < 0 else 0.0,
            'debit': 0.0,
            'credit': 0.0,
            'closing_dr': cl_num if cl_num > 0 else 0.0,
            'closing_cr': abs(cl_num) if cl_num < 0 else 0.0,
            'closing_net': cl_num,
            'prior_closing_net': 0.0
        })
    return ledgers

def save_imported_ledgers(ledgers, source_filename="Uploaded_TB"):
    conn = get_connection()
    cursor = conn.cursor()

    # Clear previous import
    cursor.execute("DELETE FROM tally_import;")
    cursor.execute("DELETE FROM ledger_mappings;")

    # Deduplicate by ledger_name (keep last occurrence, which tends to have better amounts)
    seen = {}
    for l in ledgers:
        name = str(l.get('ledger_name', '')).strip()
        if not name:
            continue
        # Skip group-separator rows that leaked in
        if name.startswith('—') or name.startswith('---') or name.startswith('–'):
            continue
        seen[name] = l   # overwrite duplicates

    clean_ledgers = list(seen.values())

    for l in clean_ledgers:
        cursor.execute("""
        INSERT OR REPLACE INTO tally_import
            (ledger_name, tally_group, opening_dr, opening_cr, debit, credit,
             closing_dr, closing_cr, closing_net, prior_closing_net, source_filename)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
        """, (
            l['ledger_name'],
            l['tally_group'],
            l.get('opening_dr', 0.0),
            l.get('opening_cr', 0.0),
            l.get('debit', 0.0),
            l.get('credit', 0.0),
            l.get('closing_dr', 0.0),
            l.get('closing_cr', 0.0),
            l.get('closing_net', 0.0),
            l.get('prior_closing_net', 0.0),
            source_filename
        ))

    conn.commit()
    conn.close()
    log_audit("IMPORT_TB", "tally_import", details=f"Imported {len(clean_ledgers)} ledgers from {source_filename} (deduplicated from {len(ledgers)} rows)")

