// Build release\CMA-Keygen.exe — interactive license key generator with the
// private key EMBEDDED (vendor-only tool; whoever has this exe can mint keys).
// Run:  node tools/build-keygen-exe.cjs
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'dist-server');
const RELEASE_DIR = path.join(ROOT, 'release');
const EXE_NAME = 'CMA-Keygen.exe';

// 1. embed the private key
const privPath = path.join(ROOT, 'tools', 'keygen-private.pem');
if (!fs.existsSync(privPath)) {
  console.error('tools/keygen-private.pem not found — run keygen --init first');
  process.exit(1);
}
const pem = fs.readFileSync(privPath, 'utf8');
fs.writeFileSync(
  path.join(ROOT, 'tools', 'keygen-private-embedded.cjs'),
  `// GENERATED by tools/build-keygen-exe.cjs — embedded private signing key (VENDOR ONLY)\nmodule.exports = ${JSON.stringify(pem)};\n`
);
console.log('✓ private key embedded');

// 2. bundle
fs.mkdirSync(OUT_DIR, { recursive: true });
require('esbuild').buildSync({
  entryPoints: [path.join(ROOT, 'tools', 'keygen-interactive.cjs')],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  outfile: path.join(OUT_DIR, 'keygen-bundle.cjs'),
  external: ['node:*'],
});
console.log('✓ keygen bundled');

// 3. SEA blob
const seaConfig = {
  main: path.join(OUT_DIR, 'keygen-bundle.cjs'),
  output: path.join(OUT_DIR, 'keygen-sea.blob'),
  disableExperimentalSEAWarning: true,
};
fs.writeFileSync(path.join(OUT_DIR, 'keygen-sea-config.json'), JSON.stringify(seaConfig, null, 2));
execSync(`"${process.execPath}" --experimental-sea-config "${path.join(OUT_DIR, 'keygen-sea-config.json')}"`, { stdio: 'inherit' });

// 4. copy node + inject
fs.mkdirSync(RELEASE_DIR, { recursive: true });
const exePath = path.join(RELEASE_DIR, EXE_NAME);
fs.copyFileSync(process.execPath, exePath);
const postject = path.join(ROOT, 'node_modules', '.bin', process.platform === 'win32' ? 'postject.cmd' : 'postject');
execSync(`"${postject}" "${exePath}" NODE_SEA_BLOB "${path.join(OUT_DIR, 'keygen-sea.blob')}" --sentinel-fuse NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2`, { stdio: 'inherit', cwd: ROOT });

const mb = (fs.statSync(exePath).size / 1024 / 1024).toFixed(1);
console.log('');
console.log(`✓ DONE → release\\${EXE_NAME} (${mb} MB)`);
console.log('  KEEP THIS PRIVATE — anyone with this exe can generate valid license keys.');
