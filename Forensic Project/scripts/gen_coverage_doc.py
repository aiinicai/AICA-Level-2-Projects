"""
Generate docs/coverage.md automatically from rules/methods_registry.yaml.
Ensures documentation is strictly in sync with the declared registry.
"""
import os
import yaml

def generate_coverage_markdown(
    registry_path: str = "rules/methods_registry.yaml",
    output_path: str = "docs/coverage.md"
):
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(registry_path, "r", encoding="utf-8") as f:
        registry = yaml.safe_load(f) or []

    implemented = [m for m in registry if m.get("status") == "implemented"]
    not_implemented = [m for m in registry if m.get("status") == "not_implemented"]

    lines = [
        "# Methods Coverage & Feasibility Registry",
        "",
        "This document is automatically generated by `scripts/gen_coverage_doc.py` from `rules/methods_registry.yaml`.",
        "",
        f"**Summary**: {len(implemented)} Implemented Methods | {len(not_implemented)} Declared (Not Implemented) Methods | Total: {len(registry)} Evaluated.",
        "",
        "---",
        "",
        "## 1. Implemented Forensic Methods (14)",
        "",
        "| ID | Method Name | Status | Prerequisites | Min Years | Min Records | Associated Rules |",
        "|---|---|---|---|---|---|---|"
    ]

    for m in implemented:
        reqs = ", ".join(m.get("requires", []))
        min_y = m.get("min_years", 1)
        min_r = m.get("min_records", "—")
        rules = ", ".join(m.get("rules", [])) if m.get("rules") else "Unsupervised / Model"
        lines.append(f"| **{m.get('id')}** | {m.get('name')} | `{m.get('status')}` | `{reqs}` | {min_y} | {min_r} | {rules} |")

    lines.extend([
        "",
        "---",
        "",
        "## 2. Evaluated & Rejected Methods — Declared Not Implemented (13)",
        "",
        "These methods were explicitly evaluated against trial-balance constraints and rejected. No stubs, dead code, or placeholder functions exist in the codebase for these methods.",
        "",
        "| ID | Method Name | Why Blocked on Trial Balance | What Dataset Unlocks It |",
        "|---|---|---|---|"
    ])

    for m in not_implemented:
        lines.append(f"| **{m.get('id')}** | {m.get('name')} | {m.get('blocked_by')} | **{m.get('unlocked_by')}** |")

    lines.append("")
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Generated coverage documentation at: {output_path}")

if __name__ == "__main__":
    generate_coverage_markdown()
