class TestDocxFormatting:
    def test_it_opens_in_word(self, sample: Path) -> None:
        assert sample.exists()
        assert DocxDocument(str(sample)) is not None

    def test_body_font_is_times_new_roman_10pt(self, sample: Path) -> None:
        # §18.9 — the DOCX must match the preview.
        style = DocxDocument(str(sample)).styles["Normal"]
        assert style.font.name == "Times New Roman"
        assert style.font.size == Pt(10)

    def test_margins_are_one_inch_with_a_gutter(self, sample: Path) -> None:
        # The prototype used 0.75 inch and no gutter.
        section = DocxDocument(str(sample)).sections[0]
        assert section.top_margin == Inches(1)
        assert section.right_margin == Inches(1)
        assert section.bottom_margin == Inches(1)
        assert section.left_margin == Inches(1.25)

    def test_a_footer_exists_on_every_section(self, sample: Path) -> None:
        for section in DocxDocument(str(sample)).sections:
            text = section.footer.paragraphs[0].text
            assert "ABC Private Limited" in text
            assert "FY 2025-26" in text

    def test_page_numbers_are_fields_not_typed_numbers(self, sample: Path) -> None:
        """A typed "Page 1 of 3" is wrong the moment Word repaginates."""
        with zipfile.ZipFile(sample) as archive:
            footers = [n for n in archive.namelist() if "footer" in n]
            assert footers
            xml = archive.read(footers[0]).decode("utf-8")
        assert "PAGE" in xml
        assert "NUMPAGES" in xml
        assert "fldChar" in xml

    def test_a_header_carries_the_document_title(self, sample: Path) -> None:
        section = DocxDocument(str(sample)).sections[0]
        assert "Independent Auditor" in section.header.paragraphs[0].text

    def test_the_document_does_not_name_the_software(self, sample: Path) -> None:
        """Partner, 19 August 2026: no tool stamp on the output.

        This test asserted the OPPOSITE until today - that every export carried
        "Generated by AuditCraft . Template <version> . <timestamp>" at its foot.
        A statutory report goes out over the firm's name and the signing
        partner's membership number; the software that typeset it is not a party
        to it.

        The version and timestamp are not lost: they are on the
        `document_instance` row, which is what a reprint is rebuilt from.
        """
        text = chr(10).join(p.text for p in DocxDocument(str(sample)).paragraphs)
        assert "AuditCraft" not in text
        assert "Generated by" not in text

    def test_signature_blocks_keep_with_next(self, sample: Path) -> None:
        # §11.1 — a signature must not split across a page break.
        paragraphs = [p for p in DocxDocument(str(sample)).paragraphs if "FRN" in p.text]
        assert paragraphs
        assert paragraphs[0].paragraph_format.keep_with_next is True

    def test_a_clause_number_gets_a_hanging_indent(self, sample: Path) -> None:
        paragraphs = [p for p in DocxDocument(str(sample)).paragraphs if p.text.startswith("(a)")]
        assert paragraphs
        assert paragraphs[0].paragraph_format.first_line_indent < 0

    def test_the_table_is_a_real_table(self, sample: Path) -> None:
        tables = DocxDocument(str(sample)).tables
        assert len(tables) == 1
        assert tables[0].rows[0].cells[0].text == "A"


