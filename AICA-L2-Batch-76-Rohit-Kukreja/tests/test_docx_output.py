class TestReprintFromSnapshot:
    def test_a_reprint_matches_its_recorded_hash(
        self, db: Session, engagement: Engagement, clause_set: ClauseSet, tmp_path: Path
    ) -> None:
        generate_document(db, engagement, "caro_2020", clause_set, generated_by="p", with_pdf=False)
        instance = db.scalar(
            select(DocumentInstance).where(
                DocumentInstance.engagement_id == engagement.engagement_id
            )
        )
        assert instance is not None

        _, matches = reprint(db, instance.doc_id, clause_set, tmp_path / "again.docx")
        assert matches is True

    def test_a_reprint_ignores_later_master_data_changes(
        self,
        db: Session,
        engagement: Engagement,
        clause_set: ClauseSet,
        client_id: int,
        tmp_path: Path,
    ) -> None:
        from datetime import date

        from app.services.client import ChangeScope, change_profile

        generate_document(db, engagement, "caro_2020", clause_set, generated_by="p", with_pdf=False)
        instance = db.scalar(
            select(DocumentInstance).where(
                DocumentInstance.engagement_id == engagement.engagement_id
            )
        )
        assert instance is not None

        change_profile(
            db,
            client_id,
            {"company_name": "Renamed Limited"},
            change_date=date(2026, 9, 1),
            changed_by="m",
            reason="Renamed",
            scope=ChangeScope.MASTER_ONLY,
        )
        db.flush()

        # §18.6 — the reprint still reproduces what was signed.
        _, matches = reprint(db, instance.doc_id, clause_set, tmp_path / "again.docx")
        assert matches is True
