class TestGeneration:
    def test_a_document_instance_is_recorded(
        self, db: Session, engagement: Engagement, clause_set: ClauseSet
    ) -> None:
        result = generate_document(
            db, engagement, "caro_2020", clause_set, generated_by="p", with_pdf=False
        )
        assert result.path.exists()
        assert len(result.content_sha256) == 64

        instance = db.scalar(
            select(DocumentInstance).where(
                DocumentInstance.engagement_id == engagement.engagement_id
            )
        )
        assert instance is not None
        assert instance.version_no == 1
        assert instance.payload_json

    def test_versions_increment(
        self, db: Session, engagement: Engagement, clause_set: ClauseSet
    ) -> None:
        first = generate_document(
            db, engagement, "caro_2020", clause_set, generated_by="p", with_pdf=False
        )
        second = generate_document(
            db, engagement, "caro_2020", clause_set, generated_by="p", with_pdf=False
        )
        assert (first.version_no, second.version_no) == (1, 2)

    def test_filenames_derive_from_ids_not_free_text(
        self, db: Session, engagement: Engagement, clause_set: ClauseSet
    ) -> None:
        # §11.4 — never from user-entered text.
        result = generate_document(
            db, engagement, "caro_2020", clause_set, generated_by="p", with_pdf=False
        )
        assert result.path.name == f"{engagement.engagement_id}_caro_2020_v1.docx"

    def test_a_blocked_document_will_not_export(
        self, db: Session, engagement: Engagement, clause_set: ClauseSet
    ) -> None:
        from app.services.engagement import set_response

        set_response(db, engagement.engagement_id, "caro.viii", "", updated_by="t")
        with pytest.raises(ExportError, match="block export"):
            generate_document(
                db, engagement, "caro_2020", clause_set, generated_by="p", with_pdf=False
            )


class TestAuditPack:
    def test_it_zips_the_available_documents(
        self, db: Session, engagement: Engagement, clause_set: ClauseSet
    ) -> None:
        pack = build_audit_pack(db, engagement, clause_set, generated_by="partner")
        assert pack.exists()
        with zipfile.ZipFile(pack) as archive:
            names = archive.namelist()
        assert "manifest.json" in names
        assert any(name.endswith("_Auditors_Report.docx") for name in names)
        assert any(name.endswith("_CARO_2020_Annexure_A.docx") for name in names)

    def test_documents_are_numbered_in_order(
        self, db: Session, engagement: Engagement, clause_set: ClauseSet
    ) -> None:
        pack = build_audit_pack(db, engagement, clause_set, generated_by="p")
        with zipfile.ZipFile(pack) as archive:
            docs = sorted(n for n in archive.namelist() if n.endswith(".docx"))
        assert docs[0].startswith("03_")  # auditor's report
        assert docs[1].startswith("04_")  # CARO annexure

    def test_the_manifest_records_hashes_and_versions(
        self, db: Session, engagement: Engagement, clause_set: ClauseSet
    ) -> None:
        pack = build_audit_pack(db, engagement, clause_set, generated_by="p")
        with zipfile.ZipFile(pack) as archive:
            manifest = json.loads(archive.read("manifest.json"))
        assert manifest["financial_year"] == "2025-26"
        assert manifest["template_version"] == "0.1.0-phase1"
        for entry in manifest["documents"]:
            assert len(entry["sha256"]) == 64
            assert entry["version"] >= 1

    def test_missing_documents_are_named_not_silently_dropped(
        self, db: Session, engagement: Engagement, clause_set: ClauseSet
    ) -> None:
        """Four of the six documents are not authored yet.

        A pack that quietly lacks the MRL and the Directors' Report would be
        worse than one that says so.
        """
        pack = build_audit_pack(db, engagement, clause_set, generated_by="p")
        with zipfile.ZipFile(pack) as archive:
            manifest = json.loads(archive.read("manifest.json"))
        missing = manifest["documents_not_in_repository"]
        assert set(missing) == {
            "engagement_letter",
            "mrl",
            "ifc_report",
            "directors_report",
        }


