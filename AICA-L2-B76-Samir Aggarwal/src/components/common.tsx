export function StatCard({
  label,
  value,
  icon: Icon,
  tone = 'default',
  hint,
}: {
  label: string
  value: React.ReactNode
  icon?: React.ComponentType<{ className?: string }>
  tone?: 'default' | 'destructive' | 'success' | 'accent'
  hint?: string
}) {
  const toneClass = {
    default: 'text-foreground',
    destructive: 'text-destructive',
    success: 'text-success',
    accent: 'text-accent',
  }[tone]

  return (
    <Card className="gap-0 py-4">
      <CardContent className="flex items-start justify-between gap-3 px-4">
        <div className="min-w-0">
          <p className="text-muted-foreground text-xs font-medium tracking-wide uppercase">
            {label}
          </p>
          <p className={cn('mt-1 text-2xl font-semibold tabular-nums', toneClass)}>{value}</p>
          {hint ? <p className="text-muted-foreground mt-0.5 text-xs">{hint}</p> : null}
        </div>
        {Icon ? (
          <div
            className={cn('bg-muted grid size-9 shrink-0 place-items-center rounded-md', toneClass)}
          >
            <Icon className="size-4" />
          </div>
        ) : null}
      </CardContent>
    </Card>
  )
}

export function StageBadge({
  code,
  name,
  showCode = false,
}: {
  code: string
  name: string
  showCode?: boolean
}) {
  const colour = stageVar(code)
  return (
    <span
      className="inline-flex items-center gap-1.5 rounded-md border px-2 py-0.5 text-xs font-medium whitespace-nowrap"
      style={{
        color: colour,
        borderColor: colour,
        backgroundColor: `color-mix(in srgb, ${colour} 10%, transparent)`,
      }}
    >
      <span className="size-1.5 rounded-full" style={{ backgroundColor: colour }} />
      {showCode ? <span className="opacity-70 tabular-nums">{code}</span> : null}
      {name}
    </span>
  )
}

/**
 * How long a task has sat in its current stage. This replaced the old
 * efficiency metrics: it measures the work getting stuck, not the person.
 */
export function AgeingBadge({
  days,
  terminal = false,
}: {
  days: number
  terminal?: boolean
}) {
  if (terminal) {
    return <span className="text-muted-foreground text-xs whitespace-nowrap">—</span>
  }

  const tone =
    days >= AGEING_ALERT
      ? 'text-destructive font-semibold'
      : days >= AGEING_WARN
        ? 'text-warning font-medium'
        : 'text-muted-foreground'

  return (
    <span className={cn('text-xs whitespace-nowrap tabular-nums', tone)}>
      {days === 0 ? 'today' : days === 1 ? '1 day' : `${days} days`}
    </span>
  )
}

