/**
 * Not yet due: "due in Xd". Shown only inside a 45-day window so far-off
 * annual items do not shout from every list.
 */
export function UpcomingBadge({ days }: { days?: number | null }) {
  if (typeof days !== 'number' || days < 0 || days > 45) return null
  return (
    <span
      className="inline-flex items-center rounded-md border px-2 py-0.5 text-xs font-medium whitespace-nowrap"
      style={{
        color: 'var(--stage-02)',
        borderColor: 'var(--stage-02)',
        backgroundColor: 'color-mix(in srgb, var(--stage-02) 8%, transparent)',
      }}
    >
      {days === 0 ? 'due today' : days === 1 ? 'due tomorrow' : `due in ${days}d`}
    </span>
  )
}

export function OverdueBadge({ days }: { days?: number | null }) {
  return (
    <Badge variant="destructive" className="whitespace-nowrap">
      {typeof days === 'number' && days < 0 ? `${Math.abs(days)}d overdue` : 'Overdue'}
    </Badge>
  )
}

