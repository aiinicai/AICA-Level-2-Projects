from __future__ import annotations
import hashlib
import json
from datetime import datetime
from pathlib import Path

from .models import SEV_ORDER, load_catalogue

FONT = "Times New Roman"


def sha256(path):
    if not path:
        return ""
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def _flatten(results):
    rows = []
    for r in results:
        if r.status == "REVIEW":
            continue                      # assisted evidence is listed in section 4, not as an exception
        for i, f in enumerate(r.findings, 1):
            rows.append((f"{f.check_id}.{i}", f))
    rows.sort(key=lambda x: (SEV_ORDER.get(x[1].severity, 9), x[0]))
    return rows


def _status_rows(results, module):
    cat = [c for c in load_catalogue() if c["mod"] == module]
    by = {r.check_id: r for r in results}
    rows = []
    for c in cat:
        r = by.get(c["id"])
        if c["id"] in ("SA-50", "LQ-20"):
            rows.append((c, "a", "Generated - this paper"))
            continue
        if r is None:
            st, note = "r", f"Manual - class {c['cls']} ({'assisted' if c['cls'] == 'B' else 'judgement' if c['cls'] == 'C' else 'rule not yet built'})"
        elif r.status == "PASS":
            st, note = "a", "Automated - no exception"
        elif r.status == "EXC":
            st, note = "EXC", f"{len(r.findings)} exception(s) - see section 2"
        elif r.status == "NA":
            st, note = "a", "Not applicable"
        elif r.status == "REVIEW":
            st, note = "ASSIST", "Reviewer to confirm: " + " ".join(f"{f.detail}" for f in r.findings)[:420]
        else:
            st, note = "r", f"Not run: {r.note}"
        rows.append((c, st, note))
    return rows


def write_memo(path, title, meta, results, module, milestones=None, inputs=None):
    import docx
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Pt, Inches, RGBColor
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement

    d = docx.Document()
    st = d.styles["Normal"]
    st.font.name = FONT
    st.font.size = Pt(10)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    sec = d.sections[0]
    sec.left_margin, sec.top_margin, sec.right_margin, sec.bottom_margin = Inches(0.8), Inches(0.8), Inches(0.8), Inches(0.8)
    sec.orientation = 1
    sec.page_width, sec.page_height = sec.page_height, sec.page_width   # landscape

    def shade(cell, hexcolor):
        tcPr = cell._tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto"); shd.set(qn("w:fill"), hexcolor)
        tcPr.append(shd)

    def heading(text):
        p = d.add_paragraph(); p.paragraph_format.space_before = Pt(12)
        r = p.add_run(text); r.bold = True; r.font.size = Pt(11)

    def table(headers, rows, widths=None, sev_col=None):
        t = d.add_table(rows=1, cols=len(headers))
        t.style = "Table Grid"
        for i, h in enumerate(headers):
            c = t.rows[0].cells[i]
            c.text = ""
            r = c.paragraphs[0].add_run(h); r.bold = True; r.font.size = Pt(9)
            shade(c, "D9E2F3")
        for row in rows:
            cells = t.add_row().cells
            for i, v in enumerate(row):
                cells[i].text = ""
                run = cells[i].paragraphs[0].add_run(str(v)); run.font.size = Pt(9)
                if sev_col is not None and i == sev_col:
                    shade(cells[i], {"High": "F8CBAD", "Medium": "FFE699", "Low": "E2EFDA"}.get(str(v), "FFFFFF"))
        if widths:
            t.autofit = False
            for i, w in enumerate(widths):
                t.columns[i].width = Inches(w)
            for row in t.rows:
                for i, w in enumerate(widths):
                    row.cells[i].width = Inches(w)
        return t

    h = d.add_paragraph(); r = h.add_run(title); r.bold = True; r.font.size = Pt(16)
    d.add_paragraph("Generated by AuditSignOff Suite UAE - Partner/Manager Review Automation (offline). Software finds and records; the reviewer decides and signs.").runs[0].italic = True

    table(["Item", "Detail"], [(k, v) for k, v in meta.items()], widths=[2.2, 7.0])
    d.add_paragraph()

    flat = _flatten(results)
    sev = {s: sum(1 for _, f in flat if f.severity == s) for s in ("High", "Medium", "Low", "Info")}
    n_pass = sum(1 for r in results if r.status == "PASS")
    n_exc = sum(1 for r in results if r.status == "EXC")
    n_nr = sum(1 for r in results if r.status == "NOTRUN")
    n_as = sum(1 for r in results if r.status == "REVIEW")
    n_na = sum(1 for r in results if r.status == "NA")
    n_man = sum(1 for c, st, n in _status_rows(results, module) if st == "r") - n_nr
    heading("1. Summary")
    table(["Checks automated", "Passed (not listed again)", "With exceptions", "Assisted - reviewer to confirm", "Not run (input missing)", "Manual only", "High", "Medium", "Low"],
          [(len(results) - n_as - n_na, n_pass, n_exc, n_as, n_nr, max(n_man, 0), sev["High"], sev["Medium"], sev["Low"])], widths=[1.0, 1.2, 1.0, 1.3, 1.2, 0.9, 0.6, 0.7, 0.6])
    verdict = "NOT READY for Partner sign-off: High-severity exceptions are open." if sev["High"] else (
        "Automated checks clear. Complete the manual and judgement items in section 4 before sign-off." )
    d.add_paragraph().add_run(verdict).bold = True

    heading("2. Exceptions requiring reviewer action")
    if flat:
        table(["Ref", "Severity", "Finding", "Detail", "Evidence / location", "Expected", "Found", "Reviewer response", "Status / cleared by"],
              [(ref, f.severity, f.title, f.detail, f.location, f.expected, f.found, "", "Open") for ref, f in flat],
              widths=[0.6, 0.6, 1.6, 2.0, 1.4, 0.9, 0.9, 1.0, 0.7], sev_col=1)
    else:
        d.add_paragraph("No exceptions raised by the automated checks.")

    if milestones:
        heading("3. Clock and milestone schedule")
        table(["Check", "Milestone", "Basis", "Due / earliest", "Actual", "Status"],
              [(m["check"], m["milestone"], m["basis"], m["due"], m["actual"], m["status"]) for m in milestones],
              widths=[0.6, 2.2, 3.4, 1.1, 1.1, 0.9])

    heading("4. Exceptions and items not fully checked by the software (checks that passed are not repeated)")
    d.add_paragraph("EXC = exception (section 2); ASSIST = software extracted the evidence, reviewer confirms; r = not run or manual.").runs[0].font.size = Pt(9)
    table(["ID", "Area", "Check", "Class", "Status", "Note / evidence"],
          [(c["id"], c["grp"], c["check"], c["cls"], s, n) for c, s, n in _status_rows(results, module) if s != "a"],
          widths=[0.6, 1.2, 3.2, 0.5, 0.7, 3.4])

    d.add_paragraph()
    heading("5. Sign-off")
    t = d.add_table(rows=4, cols=5); t.style = "Table Grid"
    cols = [("", None), ("Prepared by", "Prepared by"), ("First review", "Reviewer 1"), ("Manager review", "Reviewer 2"), ("Partner review", "Reviewer 3")]
    for i, (hname, key) in enumerate(cols):
        t.rows[0].cells[i].text = hname
        if key:
            t.rows[1].cells[i].text = str(meta.get(key, "") or "")
            if key == "Prepared by" and meta.get(key):
                t.rows[2].cells[i].text = str(meta.get("Prepared at", "") or "")
                t.rows[3].cells[i].text = "Generated in system"
    for ri, lab in enumerate(["Name", "Date", "Sign"], 1):
        t.rows[ri].cells[0].text = lab

    if inputs:
        d.add_paragraph()
        p = d.add_paragraph(); rr = p.add_run("Input integrity (SHA-256): " + "; ".join(f"{Path(k).name}: {v[:16]}..." for k, v in inputs.items() if v))
        rr.font.size = Pt(8)
    d.save(path)


def write_xlsx(path, results, module, milestones=None):
    import openpyxl
    from openpyxl.styles import Font, PatternFill, Alignment
    from openpyxl.worksheet.datavalidation import DataValidation
    wb = openpyxl.Workbook()
    ws = wb.active; ws.title = "Exceptions"
    hdr = ["Ref", "Check", "Severity", "Finding", "Detail", "Evidence / location", "Expected", "Found", "Reviewer response", "Status", "Cleared by", "Date"]
    ws.append(hdr)
    for ref, f in _flatten(results):
        ws.append([ref, f.check_id, f.severity, f.title, f.detail, f.location, f.expected, f.found, "", "Open", "", ""])
    for c in ws[1]:
        c.font = Font(bold=True); c.fill = PatternFill("solid", fgColor="D9E2F3")
    for col, w in zip("ABCDEFGHIJKL", [8, 8, 9, 40, 50, 30, 18, 18, 30, 11, 14, 11]):
        ws.column_dimensions[col].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")
    dv = DataValidation(type="list", formula1='"Open,Cleared,Waived (Partner),Disputed"', allow_blank=False)
    ws.add_data_validation(dv)
    dv.add(f"J2:J{max(ws.max_row, 2) + 200}")
    ws.freeze_panes = "A2"
    ws2 = wb.create_sheet("Check status")
    ws2.append(["ID", "Area", "Check", "Class", "Status", "Note"])
    for c, s, n in _status_rows(results, module):
        if s != "a":                                  # passed checks are not repeated (full list is in the JSON audit trail)
            ws2.append([c["id"], c["grp"], c["check"], c["cls"], s, n])
    for c in ws2[1]:
        c.font = Font(bold=True)
    ws2.column_dimensions["C"].width = 90; ws2.column_dimensions["F"].width = 40
    if milestones:
        ws3 = wb.create_sheet("Milestones")
        ws3.append(["Check", "Milestone", "Basis", "Due / earliest", "Actual", "Status"])
        for m in milestones:
            ws3.append([m["check"], m["milestone"], m["basis"], m["due"], m["actual"], m["status"]])
        for c in ws3[1]:
            c.font = Font(bold=True)
        ws3.column_dimensions["B"].width = 40; ws3.column_dimensions["C"].width = 70
    wb.save(path)


def write_json(path, meta, results, milestones=None, inputs=None):
    payload = {"generated": datetime.now().isoformat(timespec="seconds"), "meta": meta, "inputs_sha256": inputs or {},
               "results": [{"check": r.check_id, "status": r.status, "note": r.note, "findings": [f.to_dict() for f in r.findings]} for r in results],
               "milestones": milestones or []}
    Path(path).write_text(json.dumps(payload, indent=2), encoding="utf-8")


def verify_outputs(docx_path, xlsx_path, json_path):
    """Re-open each file produced; raises if one is missing, empty or unreadable so a broken review file is never handed over silently."""
    import json as _json
    from pathlib import Path as _P
    import docx as _docx
    import openpyxl as _ox
    for q in (docx_path, xlsx_path, json_path):
        if not _P(q).exists() or _P(q).stat().st_size < 200:
            raise RuntimeError(f"Review file was not created properly: {q}")
    d = _docx.Document(str(docx_path))
    if len(d.paragraphs) < 3 or not d.tables:
        raise RuntimeError("Review paper is empty - no heading or tables found")
    _ox.load_workbook(str(xlsx_path))
    _json.loads(_P(json_path).read_text(encoding="utf-8"))
