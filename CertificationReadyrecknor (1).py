# Automatically installs missing third-party packages when run as a .py
# script. Skipped entirely when running from a PyInstaller-frozen .exe,
# where dependencies are already bundled.
# --------------------------------------------------------------------------
def _ensure_dependencies():
    if getattr(sys, "frozen", False):
        return
    required = {"PyQt6": "PyQt6", "docx": "python-docx"}
    missing = []
    for import_name, pip_name in required.items():
        try:
            __import__(import_name)
        except ImportError:
            missing.append(pip_name)
    if missing:
        import subprocess
        print("Certification Readyrecknor: installing missing dependencies: "
              + ", ".join(missing))
        try:
            subprocess.check_call([sys.executable, "-m", "pip", "install", "--quiet", *missing])
            print("Dependencies installed successfully. Starting application...")
        except Exception as exc:
            print("Automatic installation failed: {}".format(exc))
            print("Please install manually with:")
            print("    {} -m pip install {}".format(sys.executable, " ".join(missing)))
            sys.exit(1)


_ensure_dependencies()

