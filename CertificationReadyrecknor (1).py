def to_float(value, default=0.0):
    try:
        if value is None or value == "":
            return default
        return float(str(value).replace(",", "").replace("₹", "").strip())
    except (ValueError, TypeError):
        return default


def indian_comma_format(number, decimals=2):
    """Formats a number using the Indian digit-grouping convention
    (last 3 digits, then groups of 2), e.g. 1234567.89 -> 12,34,567.89"""
    try:
        number = float(number)
    except (ValueError, TypeError):
        number = 0.0
    negative = number < 0
    number = abs(number)
    whole = "{:.{}f}".format(number, decimals)
    if decimals:
        integer_part, decimal_part = whole.split(".")
    else:
        integer_part, decimal_part = whole, ""
    if len(integer_part) <= 3:
        grouped = integer_part
    else:
        last3 = integer_part[-3:]
        rest = integer_part[:-3]
        chunks = []
        while len(rest) > 2:
            chunks.insert(0, rest[-2:])
            rest = rest[:-2]
        if rest:
            chunks.insert(0, rest)
        grouped = ",".join(chunks) + "," + last3
    result = grouped + ("." + decimal_part if decimals else "")
    if negative:
        result = "-" + result
    return result


def rupee_display(number, decimals=2):
    return "₹ " + indian_comma_format(number, decimals)


def number_to_words_indian(number):
    """Converts an integer (rupee value) into words using the Indian
    numbering system (Crore / Lakh / Thousand)."""
    try:
        n = int(round(float(number)))
    except (ValueError, TypeError):
        n = 0
    if n == 0:
        return "Zero"
    ones = ["", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight",
            "Nine", "Ten", "Eleven", "Twelve", "Thirteen", "Fourteen", "Fifteen",
            "Sixteen", "Seventeen", "Eighteen", "Nineteen"]
    tens = ["", "", "Twenty", "Thirty", "Forty", "Fifty", "Sixty", "Seventy",
            "Eighty", "Ninety"]

    def two_digits(num):
        if num < 20:
            return ones[num]
        t = tens[num // 10]
        o = ones[num % 10]
        return (t + (" " + o if o else "")).strip()

    def three_digits(num):
        if num >= 100:
            h = ones[num // 100] + " Hundred"
            rem = num % 100
            return (h + (" " + two_digits(rem) if rem else "")).strip()
        return two_digits(num)

    negative = n < 0
    n = abs(n)
    crore, n = divmod(n, 10000000)
    lakh, n = divmod(n, 100000)
    thousand, n = divmod(n, 1000)
    remainder = n

    parts = []
    if crore:
        parts.append(three_digits(crore) + " Crore")
    if lakh:
        parts.append(two_digits(lakh) + " Lakh")
    if thousand:
        parts.append(two_digits(thousand) + " Thousand")
    if remainder:
        parts.append(three_digits(remainder))

    words = " ".join(parts).strip()
    if negative:
        words = "Minus " + words
    return words


def amount_in_words_rupees(number):
    return "Rupees " + number_to_words_indian(number) + " Only"


def validate_pan(value):
    return bool(re.match(r"^[A-Z]{5}[0-9]{4}[A-Z]$", (value or "").strip().upper()))


def validate_gstin(value):
    return bool(re.match(
        r"^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z]{1}[1-9A-Z]{1}Z[0-9A-Z]{1}$",
        (value or "").strip().upper()))


def validate_cin(value):
    return bool(re.match(
        r"^[LUlu][0-9]{5}[A-Za-z]{2}[0-9]{4}[A-Za-z]{3}[0-9]{6}$",
        (value or "").strip()))


def validate_udin(value):
    """UDIN format check only: exactly 18 alphanumeric characters.
    This does NOT verify the UDIN against the ICAI UDIN portal."""
    return bool(re.match(r"^[A-Za-z0-9]{18}$", (value or "").strip()))


def sanitize_filename(name):
    name = re.sub(r'[\\/*?:"<>|]', "_", name or "")
    name = re.sub(r"\s+", "_", name.strip())
    return name[:120] if name else "Certificate"


def unique_filepath(folder, filename):
    base, ext = os.path.splitext(filename)
    candidate = os.path.join(folder, filename)
    counter = 1
    while os.path.exists(candidate):
        candidate = os.path.join(folder, "{}_{}{}".format(base, counter, ext))
        counter += 1
    return candidate


def open_file_externally(path):
    try:
        if sys.platform.startswith("win"):
            os.startfile(path)  # noqa
        elif sys.platform == "darwin":
            _subprocess.Popen(["open", path])
        else:
            _subprocess.Popen(["xdg-open", path])
    except Exception as exc:
        QMessageBox.warning(None, "Could not open file", str(exc))


