class DetailsFormPage(QScrollArea):
    """Dynamically renders the input form for the currently selected
    certificate type, built from fields_for_type()."""

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setWidgetResizable(True)
        self.cert_type = None
        self.field_widgets = {}
        self.table_editors = {}
        self.inner = QWidget()
        self.setWidget(self.inner)
        self.form_layout = QVBoxLayout(self.inner)
        self.form_layout.setContentsMargins(4, 4, 4, 4)

    def _clear_layout(self, layout):
        """Recursively removes and deletes every widget/sub-layout from a
        layout so the form can be safely rebuilt on each load() call."""
        while layout.count():
            item = layout.takeAt(0)
            w = item.widget()
            if w is not None:
                w.deleteLater()
            else:
                sub_layout = item.layout()
                if sub_layout is not None:
                    self._clear_layout(sub_layout)

    def load(self, cert_type, existing_data=None):
        self.cert_type = cert_type
        existing_data = existing_data or {}
        self.field_widgets = {}
        self.table_editors = {}
        self._clear_layout(self.form_layout)

        header_row = QHBoxLayout()
        title = QLabel(cert_type_name(cert_type))
        title.setObjectName("SectionTitle")
        header_row.addWidget(title)
        header_row.addStretch()
        sample_btn = QPushButton("Fill Sample Data (Demo)")
        sample_btn.setObjectName("Secondary")
        sample_btn.setToolTip(
            "Fills this form with ready-made, clearly fictitious demo data so you "
            "can walk through the whole wizard and see a finished sample certificate.")
        sample_btn.clicked.connect(lambda: self.load(cert_type, sample_data_for_type(cert_type)))
        header_row.addWidget(sample_btn)
        self.form_layout.addLayout(header_row)

        group = QGroupBox("Certificate Particulars")
        form = QFormLayout()
        form.setLabelAlignment(Qt.AlignmentFlag.AlignLeft)
        group.setLayout(form)
        self.form_layout.addWidget(group)

        table_fields = []
        for field in fields_for_type(cert_type):
            key = field["key"]
            ftype = field["type"]
            required = field.get("required", False)
            label_text = field["label"] + (" *" if required else "")
            if ftype == "table":
                table_fields.append(field)
                continue
            elif ftype == "textarea":
                w = QTextEdit()
                w.setFixedHeight(60)
                w.setPlainText(str(existing_data.get(key, "")))
            elif ftype == "date":
                w = QDateEdit()
                w.setCalendarPopup(True)
                w.setDisplayFormat("dd-MM-yyyy")
                existing_val = existing_data.get(key, "")
                qd = QDate.fromString(existing_val, "dd-MM-yyyy") if existing_val else QDate.currentDate()
                w.setDate(qd if qd.isValid() else QDate.currentDate())
            elif ftype == "select":
                w = QComboBox()
                w.addItems(field.get("options", []))
                existing_val = existing_data.get(key, "")
                if existing_val in field.get("options", []):
                    w.setCurrentText(existing_val)
            else:  # text / number
                w = QLineEdit()
                w.setText(str(existing_data.get(key, "")))
            self.field_widgets[key] = (w, field)
            form.addRow(label_text, w)

        for field in table_fields:
            key = field["key"]
            box = QGroupBox(field["label"])
            box_layout = QVBoxLayout()
            box.setLayout(box_layout)
            editor = TableEditorWidget(field["columns"],
                                        on_change=lambda ed, k=key: self._recompute(k, ed))
            editor.set_rows(existing_data.get(key, []))
            box_layout.addWidget(editor)
            self.table_editors[key] = editor
            self.form_layout.addWidget(box)
        self.form_layout.addStretch()

    def _recompute(self, key, editor):
        """Live recalculation for computed columns / summary totals,
        specific to certain certificate types."""
        if self.cert_type.startswith("networth") and key in ("assets", "liabilities"):
            assets_editor = self.table_editors.get("assets")
            liab_editor = self.table_editors.get("liabilities")
            if assets_editor and liab_editor:
                total_assets = sum(to_float(r.get("amount")) for r in assets_editor.get_rows())
                total_liab = sum(to_float(r.get("amount")) for r in liab_editor.get_rows())
                net = total_assets - total_liab
                assets_editor.set_summary("Total Assets: " + rupee_display(total_assets))
                liab_editor.set_summary(
                    "Total Liabilities: " + rupee_display(total_liab)
                    + "   |   Net Worth: " + rupee_display(net))
        elif key == "shareholders":
            rows = editor.get_rows()
            total_shares = sum(to_float(r.get("shares")) for r in rows)
            for idx, r in enumerate(rows):
                shares = to_float(r.get("shares"))
                pct = (shares / total_shares * 100) if total_shares else 0
                editor.set_cell_text(idx, 4, "{:.2f}".format(pct))
            warn = "" if abs(total_shares) > 0 else "  (enter share counts to compute %)"
            editor.set_summary("Total Shares: " + indian_comma_format(total_shares, 0) + warn)
        elif key == "turnover_rows" and self.cert_type == "turnover_multi":
            rows = editor.get_rows()
            total = sum(to_float(r.get("amount")) for r in rows)
            editor.set_summary("Total Turnover: " + rupee_display(total))

    def collect_data(self):
        data = {}
        for key, (w, field) in self.field_widgets.items():
            ftype = field["type"]
            if ftype == "textarea":
                data[key] = w.toPlainText().strip()
            elif ftype == "date":
                data[key] = w.date().toString("dd-MM-yyyy")
            elif ftype == "select":
                data[key] = w.currentText()
            else:
                data[key] = w.text().strip()
        for key, editor in self.table_editors.items():
            data[key] = editor.get_rows()
        return data

    def validate(self):
        missing = []
        for key, (w, field) in self.field_widgets.items():
            if not field.get("required"):
                continue
            ftype = field["type"]
            value = w.toPlainText().strip() if ftype == "textarea" else (
                w.currentText().strip() if ftype == "select" else (
                    "" if ftype == "date" else w.text().strip()))
            if ftype != "date" and not value:
                missing.append(field["label"])
                w.setStyleSheet("border: 1px solid {};".format(COLOR_DANGER))
            else:
                w.setStyleSheet("")
        errors = []
        if missing:
            errors.append("Please fill in required field(s): " + ", ".join(missing))
        pan_field = self.field_widgets.get("client_pan")
        if pan_field:
            pan_val = pan_field[0].text().strip()
            if pan_val and not validate_pan(pan_val):
                errors.append("Client PAN does not match the expected format (AAAAA9999A).")
        return errors


