# SECTION 7: DATABASE LAYER (SQLite, parameterised queries throughout)
# --------------------------------------------------------------------------
class Database:
    def __init__(self, path):
        self.path = path
        self.conn = sqlite3.connect(self.path)
        self.conn.execute("PRAGMA foreign_keys = ON")
        self._init_schema()

    def _init_schema(self):
        c = self.conn.cursor()
        c.execute("""CREATE TABLE IF NOT EXISTS firm_settings (
            key TEXT PRIMARY KEY, value TEXT)""")
        c.execute("""CREATE TABLE IF NOT EXISTS clients (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT, address TEXT, pan TEXT, id_no TEXT,
            created_at TEXT)""")
        c.execute("""CREATE TABLE IF NOT EXISTS certificates (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            cert_type TEXT NOT NULL,
            reference_no TEXT,
            status TEXT NOT NULL DEFAULT 'draft',
            data_json TEXT,
            wording_json TEXT,
            udin TEXT,
            approved_by TEXT,
            approved_membership_no TEXT,
            ca_approved INTEGER DEFAULT 0,
            pdf_path TEXT,
            generated_by TEXT,
            created_at TEXT,
            updated_at TEXT)""")
        c.execute("""CREATE TABLE IF NOT EXISTS templates (
            cert_type TEXT PRIMARY KEY,
            wording_json TEXT)""")
        c.execute("""CREATE TABLE IF NOT EXISTS audit_log (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            ts TEXT,
            user_name TEXT,
            action TEXT,
            cert_type TEXT,
            client_name TEXT,
            reference_no TEXT,
            detail TEXT)""")
        # Migration for databases created by an earlier version of this
        # application that predates the generated_by / audit_log additions.
        try:
            c.execute("ALTER TABLE certificates ADD COLUMN generated_by TEXT")
        except sqlite3.OperationalError:
            pass  # column already exists
        self.conn.commit()

    # ---- Settings ----
    def get_setting(self, key, default=""):
        cur = self.conn.execute("SELECT value FROM firm_settings WHERE key=?", (key,))
        row = cur.fetchone()
        return row[0] if row else default

    def get_all_settings(self):
        cur = self.conn.execute("SELECT key, value FROM firm_settings")
        return {k: v for k, v in cur.fetchall()}

    def set_setting(self, key, value):
        self.conn.execute(
            "INSERT INTO firm_settings(key, value) VALUES(?, ?) "
            "ON CONFLICT(key) DO UPDATE SET value=excluded.value", (key, value))
        self.conn.commit()

    # ---- Certificates ----
    def create_certificate(self, cert_type, data_dict, wording_dict, generated_by=""):
        now = now_iso()
        self.conn.execute(
            "INSERT INTO certificates(cert_type, reference_no, status, data_json, "
            "wording_json, udin, ca_approved, generated_by, created_at, updated_at) "
            "VALUES(?, ?, 'draft', ?, ?, '', 0, ?, ?, ?)",
            (cert_type, "", json.dumps(data_dict), json.dumps(wording_dict),
             generated_by, now, now))
        self.conn.commit()
        return self.conn.execute("SELECT last_insert_rowid()").fetchone()[0]

    # ---- Audit log: a record of which staff member created/finalized
    # each certificate, for internal accountability (not an access-control
    # or authentication mechanism). ----
    def log_action(self, user_name, action, cert_type="", client_name="",
                    reference_no="", detail=""):
        self.conn.execute(
            "INSERT INTO audit_log(ts, user_name, action, cert_type, client_name, "
            "reference_no, detail) VALUES(?, ?, ?, ?, ?, ?, ?)",
            (now_iso(), user_name or "Unknown User", action, cert_type,
             client_name, reference_no, detail))
        self.conn.commit()

    def get_audit_log(self, limit=500):
        cur = self.conn.execute(
            "SELECT * FROM audit_log ORDER BY id DESC LIMIT ?", (limit,))
        cols = [d[0] for d in cur.description]
        return [dict(zip(cols, r)) for r in cur.fetchall()]

    def update_certificate(self, cert_id, data_dict=None, wording_dict=None,
                            udin=None, approved_by=None, approved_membership_no=None,
                            ca_approved=None, status=None, pdf_path=None,
                            reference_no=None, generated_by=None):
        fields, values = [], []
        if data_dict is not None:
            fields.append("data_json=?"); values.append(json.dumps(data_dict))
        if wording_dict is not None:
            fields.append("wording_json=?"); values.append(json.dumps(wording_dict))
        if udin is not None:
            fields.append("udin=?"); values.append(udin)
        if approved_by is not None:
            fields.append("approved_by=?"); values.append(approved_by)
        if approved_membership_no is not None:
            fields.append("approved_membership_no=?"); values.append(approved_membership_no)
        if ca_approved is not None:
            fields.append("ca_approved=?"); values.append(1 if ca_approved else 0)
        if status is not None:
            fields.append("status=?"); values.append(status)
        if pdf_path is not None:
            fields.append("pdf_path=?"); values.append(pdf_path)
        if reference_no is not None:
            fields.append("reference_no=?"); values.append(reference_no)
        if generated_by is not None:
            fields.append("generated_by=?"); values.append(generated_by)
        fields.append("updated_at=?"); values.append(now_iso())
        values.append(cert_id)
        self.conn.execute(
            "UPDATE certificates SET {} WHERE id=?".format(", ".join(fields)), values)
        self.conn.commit()

    def get_certificate(self, cert_id):
        cur = self.conn.execute("SELECT * FROM certificates WHERE id=?", (cert_id,))
        row = cur.fetchone()
        if not row:
            return None
        cols = [d[0] for d in cur.description]
        return dict(zip(cols, row))

    def delete_certificate(self, cert_id):
        self.conn.execute("DELETE FROM certificates WHERE id=?", (cert_id,))
        self.conn.commit()

    def list_certificates(self, status=None):
        if status:
            cur = self.conn.execute(
                "SELECT * FROM certificates WHERE status=? ORDER BY updated_at DESC", (status,))
        else:
            cur = self.conn.execute("SELECT * FROM certificates ORDER BY updated_at DESC")
        cols = [d[0] for d in cur.description]
        return [dict(zip(cols, r)) for r in cur.fetchall()]

    def duplicate_certificate(self, cert_id):
        rec = self.get_certificate(cert_id)
        if not rec:
            return None
        return self.create_certificate(
            rec["cert_type"], json.loads(rec["data_json"] or "{}"),
            json.loads(rec["wording_json"] or "{}"))

    def counts(self):
        total = self.conn.execute("SELECT COUNT(*) FROM certificates").fetchone()[0]
        drafts = self.conn.execute(
            "SELECT COUNT(*) FROM certificates WHERE status='draft'").fetchone()[0]
        finalized = self.conn.execute(
            "SELECT COUNT(*) FROM certificates WHERE status='finalized'").fetchone()[0]
        types_used = self.conn.execute(
            "SELECT COUNT(DISTINCT cert_type) FROM certificates").fetchone()[0]
        return {"total": total, "drafts": drafts, "finalized": finalized, "types": types_used}

    def next_reference_no(self, cert_type):
        prefix = CERTIFICATE_PREFIX.get(cert_type, "CERT")
        firm_code = self.get_setting("firm_code", "MAAK")
        today = date.today()
        fy_start = today.year if today.month >= 4 else today.year - 1
        fy_label = "{}-{}".format(fy_start, str(fy_start + 1)[-2:])
        like_pattern = "{}/{}/{}/%".format(firm_code, prefix, fy_label)
        cur = self.conn.execute(
            "SELECT reference_no FROM certificates WHERE reference_no LIKE ? "
            "ORDER BY id DESC LIMIT 1", (like_pattern,))
        row = cur.fetchone()
        seq = 1
        if row and row[0]:
            try:
                seq = int(row[0].split("/")[-1]) + 1
            except (ValueError, IndexError):
                seq = 1
        return "{}/{}/{}/{:03d}".format(firm_code, prefix, fy_label, seq)

    # ---- Templates ----
    def get_template(self, cert_type):
        cur = self.conn.execute(
            "SELECT wording_json FROM templates WHERE cert_type=?", (cert_type,))
        row = cur.fetchone()
        if row and row[0]:
            return json.loads(row[0])
        return default_wording(cert_type)

    def save_template(self, cert_type, wording_dict):
        self.conn.execute(
            "INSERT INTO templates(cert_type, wording_json) VALUES(?, ?) "
            "ON CONFLICT(cert_type) DO UPDATE SET wording_json=excluded.wording_json",
            (cert_type, json.dumps(wording_dict)))
        self.conn.commit()

    def reset_template(self, cert_type):
        self.conn.execute("DELETE FROM templates WHERE cert_type=?", (cert_type,))
        self.conn.commit()
        return default_wording(cert_type)


# --------------------------------------------------------------------------
# SECTION 8: PYTHON-DOCX CERTIFICATE GENERATION ENGINE
# Produces Microsoft Word (.docx) certificates in the firm's house format
# (modelled on the firm's existing Net Worth certificate generator):
# Title -> (Purpose) -> To, Addressee -> Verification paragraph -> main
# table -> amount in words (where applicable) -> Notes & Declarations ->
# firm signature block. No certificate reference number is printed on the
# document itself.
# --------------------------------------------------------------------------
def _docx_shade(cell, hex_fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), hex_fill)
    tc_pr.append(shd)


def _docx_run(run, size=11, bold=False, italic=False, color=None):
    run.font.name = "Arial"
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = color


def _docx_para(doc, text="", size=11, bold=False, italic=False, align=None, color=None, after=6):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(after)
    if align is not None:
        p.alignment = align
    if text:
        _docx_run(p.add_run(text), size, bold, italic, color)
    return p


def _docx_set_width(cell, inches_value):
    cell.width = Inches(inches_value)


def _docx_table_header(doc, headers, col_widths):
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = "Table Grid"
    table.autofit = False
    for cell, text, width in zip(table.rows[0].cells, headers, col_widths):
        _docx_set_width(cell, width)
        _docx_shade(cell, FILL_NAVY)
        cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        _docx_run(cell.paragraphs[0].add_run(text), 10, True, color=DOCX_WHITE)
    return table


def _docx_add_row(table, values, col_widths, bold=False, shade_hex=None, align_right_from=None):
    cells = table.add_row().cells
    for cell, width in zip(cells, col_widths):
        _docx_set_width(cell, width)
        if shade_hex:
            _docx_shade(cell, shade_hex)
    for idx, value in enumerate(values):
        cell = cells[idx]
        if align_right_from is not None and idx >= align_right_from:
            cell.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.RIGHT
        _docx_run(cell.paragraphs[0].add_run(str(value)), 10, bold)
    return cells


class BaseCertificateDocx:
    """Common title block, notes/declarations and firm signature block
    shared by every certificate type, modelled on the firm's house Word
    certificate format. Subclasses implement build_body(doc) to add the
    certificate-specific table(s)."""

    def __init__(self, cert_type, data, wording, firm_settings, approval):
        self.cert_type = cert_type
        self.data = data or {}
        self.wording = wording or default_wording(cert_type)
        self.firm = firm_settings or {}
        self.approval = approval or {}

    def fmt(self, text):
        try:
            return (text or "").format(**self.data)
        except (KeyError, IndexError):
            return text or ""

    def build_document(self):
        doc = Document()
        doc.styles["Normal"].font.name = "Arial"
        doc.styles["Normal"].font.size = Pt(11)
        section = doc.sections[0]
        section.top_margin = section.bottom_margin = Inches(0.8)
        section.left_margin = section.right_margin = Inches(0.9)

        _docx_para(doc, self.wording.get("title", "CERTIFICATE"), 14, True,
                   align=WD_ALIGN_PARAGRAPH.CENTER, color=DOCX_NAVY, after=14)

        _docx_para(doc, "To,", 11, True, after=2)
        _docx_para(doc, self.data.get("recipient", "") or "[Addressee]", 11, True, after=12)

        intro_text = self.fmt(self.wording.get("intro", ""))
        for block in intro_text.split("\n\n"):
            block = block.strip()
            if block:
                _docx_para(doc, block, 11, after=10)

        self.build_body(doc)

        notes_text = self.fmt(self.wording.get("notes", ""))
        note_lines = [n.strip() for n in notes_text.split("\n") if n.strip()]
        disclaimer = (self.firm.get("default_disclaimer") or "").strip()
        if disclaimer:
            note_lines.append(disclaimer)
        if note_lines:
            _docx_para(doc, "NOTES & DECLARATIONS", 11, True, color=DOCX_NAVY, after=4)
            for note in note_lines:
                p = doc.add_paragraph()
                p.paragraph_format.left_indent = Inches(0.25)
                p.paragraph_format.space_after = Pt(4)
                _docx_run(p.add_run("•  "), 10)
                _docx_run(p.add_run(note), 10)
            doc.add_paragraph()

        self.build_signature(doc)
        return doc

    def build_body(self, doc):
        raise NotImplementedError

    def build_signature(self, doc):
        firm_name = self.firm.get("firm_name", "[Firm Name]")
        frn = self.firm.get("frn", "")
        signatory = self.approval.get("approved_by") or self.firm.get("signatory_name", "")
        designation = self.firm.get("signatory_designation", "Partner")
        membership_no = self.approval.get("approved_membership_no") or self.firm.get("membership_no", "")
        udin = self.approval.get("udin", "")
        place = self.data.get("place", "")
        cert_date = self.data.get("certificate_date", today_str())

        _docx_para(doc, "For, {}".format(firm_name), 11, True, after=2)
        _docx_para(doc, "Chartered Accountants", 11, True, after=2)
        _docx_para(doc, "FRN No.: {}".format(frn) if frn else "", 10, after=18)
        _docx_para(doc, signatory or "[ Signatory Name ]", 11, True, after=2)
        _docx_para(doc, designation, 11, True, after=2)
        if membership_no:
            _docx_para(doc, "M No. {}".format(membership_no), 10, after=2)
        _docx_para(doc, "UDIN: {}".format(udin) if udin else "UDIN: ____________________", 10, after=2)
        _docx_para(doc, "Date: {}".format(cert_date), 10, after=2)
        _docx_para(doc, "Place: {}".format(place or "____________"), 10, after=2)

    def save(self, filepath):
        doc = self.build_document()
        doc.save(filepath)


class NetWorthCertificateDocx(BaseCertificateDocx):
    def build_body(self, doc):
        assets = self.data.get("assets", [])
        liabilities = self.data.get("liabilities", [])
        total_assets = sum(to_float(a.get("amount")) for a in assets)
        total_liabilities = sum(to_float(l.get("amount")) for l in liabilities)
        net_worth = total_assets - total_liabilities

        col_widths = [0.5, 3.0, 1.9, 1.3]
        table = _docx_table_header(
            doc, ["Sr.", "Particulars", "Basis Of Valuation", "Amount (₹)"], col_widths)

        def section_row(letter, label):
            _docx_add_row(table, [letter, label, "", ""], col_widths, bold=True, shade_hex=FILL_LIGHT)

        n = 0
        section_row("A", "ASSETS")
        for a in assets:
            n += 1
            _docx_add_row(table, [n, a.get("description", ""), a.get("basis", ""),
                                   rupee_display(to_float(a.get("amount")))], col_widths,
                          align_right_from=3)
        _docx_add_row(table, ["", "TOTAL ASSETS (A)", "", rupee_display(total_assets)],
                      col_widths, bold=True, shade_hex=FILL_LIGHT, align_right_from=3)

        section_row("B", "LIABILITIES")
        for l in liabilities:
            n += 1
            _docx_add_row(table, [n, l.get("description", ""), l.get("basis", ""),
                                   rupee_display(to_float(l.get("amount")))], col_widths,
                          align_right_from=3)
        _docx_add_row(table, ["", "TOTAL LIABILITIES (B)", "", rupee_display(total_liabilities)],
                      col_widths, bold=True, shade_hex=FILL_LIGHT, align_right_from=3)
        _docx_add_row(table, ["", "NET WORTH (A − B)", "", rupee_display(net_worth)],
                      col_widths, bold=True, shade_hex=FILL_LIGHT, align_right_from=3)

