class MainWindow(QMainWindow):
    def __init__(self, db):
        super().__init__()
        self.db = db
        self.setWindowTitle(APP_NAME)
        self.resize(1200, 780)

        central = QWidget()
        self.setCentralWidget(central)
        main_layout = QHBoxLayout(central)
        main_layout.setContentsMargins(0, 0, 0, 0)
        main_layout.setSpacing(0)

        self.sidebar = Sidebar(self.navigate)
        main_layout.addWidget(self.sidebar)

        content_wrap = QScrollArea()
        content_wrap.setWidgetResizable(True)
        self.content_inner = QWidget()
        content_wrap.setWidget(self.content_inner)
        self.content_layout = QVBoxLayout(self.content_inner)
        self.content_layout.setContentsMargins(26, 22, 26, 22)
        main_layout.addWidget(content_wrap, stretch=1)

        self.pages = {}
        self.dashboard_page = DashboardPage(self.db, lambda: self.navigate("Generate Certificate"))
        self.drafts_page = SavedDraftsPage(self.db, self._resume_draft)
        self.history_page = CertificateHistoryPage(self.db)
        self.audit_log_page = AuditLogPage(self.db)
        self.templates_page = TemplatesPage(self.db)
        self.settings_page = SettingsPage(self.db)
        self.wizard_page = CertificateWizard(self.db)
        self.wizard_page.finished.connect(self._wizard_finished)

        self.stack = QStackedWidget()
        for key, widget in [("Dashboard", self.dashboard_page),
                             ("Generate Certificate", self.wizard_page),
                             ("Saved Drafts", self.drafts_page),
                             ("Certificate History", self.history_page),
                             ("Activity Log", self.audit_log_page),
                             ("Templates", self.templates_page),
                             ("Settings", self.settings_page)]:
            self.stack.addWidget(widget)
            self.pages[key] = widget
        self.content_layout.addWidget(self.stack)

        self.navigate("Dashboard")

    def navigate(self, name):
        if name == "Generate Certificate" and self.stack.currentWidget() is not self.wizard_page:
            self.wizard_page.start_new()
        self.sidebar.set_active(name)
        self.stack.setCurrentWidget(self.pages[name])
        if name == "Dashboard":
            self.dashboard_page.refresh()
        elif name == "Saved Drafts":
            self.drafts_page.refresh()
        elif name == "Certificate History":
            self.history_page.refresh()
        elif name == "Activity Log":
            self.audit_log_page.refresh()

    def _resume_draft(self, cert_id):
        self.wizard_page.resume_draft(cert_id)
        self.sidebar.set_active("Generate Certificate")
        self.stack.setCurrentWidget(self.wizard_page)

    def _wizard_finished(self):
        self.navigate("Dashboard")


