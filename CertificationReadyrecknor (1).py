def _prompt_staff_user(db):
    """Asks which staff member is operating the application this session,
    so every certificate created/finalized can be attributed to them in
    the Activity Log and Certificate History. This is a simple
    accountability prompt, not a password-protected login: anyone can
    type any name. The last name used is remembered as a convenience
    default for next time."""
    global CURRENT_STAFF_USER
    last_used = db.get_setting("last_staff_user", "")
    name, ok = QInputDialog.getText(
        None, "Staff Sign-In - " + APP_NAME,
        "Enter your name to begin this session.\n"
        "This is recorded against every certificate you create or generate,\n"
        "for internal office accountability (it is not a password/login):",
        text=last_used)
    name = (name or "").strip()
    if not ok or not name:
        name = "Unknown User"
    CURRENT_STAFF_USER = name
    db.set_setting("last_staff_user", name)


