class TableEditorWidget(QWidget):
    """Generic add/remove-row table editor driven by a column config list
    of (key, label, type) tuples. type is one of: text, number, computed.
    Supports an optional on_change callback fired after any edit, used to
    recompute totals / percentages / derived labels."""

    def __init__(self, columns, on_change=None, parent=None):
        super().__init__(parent)
        self.columns = columns
        self.on_change = on_change
        layout = QVBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 0)

        self.table = QTableWidget(0, len(columns))
        self.table.setHorizontalHeaderLabels([c[1] for c in columns])
        self.table.horizontalHeader().setSectionResizeMode(QHeaderView.ResizeMode.Stretch)
        self.table.setMinimumHeight(140)
        self.table.itemChanged.connect(self._handle_item_changed)
        layout.addWidget(self.table)

        btn_row = QHBoxLayout()
        add_btn = QPushButton("+ Add Row")
        add_btn.setObjectName("Secondary")
        add_btn.clicked.connect(self.add_row)
        remove_btn = QPushButton("Remove Selected Row")
        remove_btn.setObjectName("Secondary")
        remove_btn.clicked.connect(self.remove_selected_row)
        btn_row.addWidget(add_btn)
        btn_row.addWidget(remove_btn)
        btn_row.addStretch()
        layout.addLayout(btn_row)

        self.summary_label = QLabel("")
        self.summary_label.setStyleSheet("font-weight:700; color:#0B1F4B; padding-top:4px;")
        layout.addWidget(self.summary_label)

    def _handle_item_changed(self, _item):
        if self.on_change:
            self.table.blockSignals(True)
            try:
                self.on_change(self)
            finally:
                self.table.blockSignals(False)

    def add_row(self, row_data=None):
        row = self.table.rowCount()
        self.table.insertRow(row)
        for col_idx, (key, label, ctype) in enumerate(self.columns):
            value = ""
            if row_data and key in row_data:
                value = row_data[key]
            item = QTableWidgetItem(str(value))
            if ctype == "computed":
                item.setFlags(Qt.ItemFlag.ItemIsEnabled | Qt.ItemFlag.ItemIsSelectable)
            self.table.setItem(row, col_idx, item)
        if self.on_change:
            self.on_change(self)

    def remove_selected_row(self):
        rows = sorted({idx.row() for idx in self.table.selectedIndexes()}, reverse=True)
        if not rows:
            if self.table.rowCount() > 0:
                rows = [self.table.rowCount() - 1]
            else:
                return
        for r in rows:
            self.table.removeRow(r)
        if self.on_change:
            self.on_change(self)

    def set_rows(self, rows_list):
        self.table.blockSignals(True)
        self.table.setRowCount(0)
        for row_data in rows_list or []:
            self.add_row(row_data)
        self.table.blockSignals(False)
        if self.on_change:
            self.on_change(self)

    def get_rows(self):
        rows = []
        for r in range(self.table.rowCount()):
            row_data = {}
            for col_idx, (key, label, ctype) in enumerate(self.columns):
                item = self.table.item(r, col_idx)
                row_data[key] = item.text() if item else ""
            rows.append(row_data)
        return rows

    def set_summary(self, text):
        self.summary_label.setText(text)

    def set_cell_text(self, row, col_idx, text):
        item = self.table.item(row, col_idx)
        if item:
            item.setText(text)


