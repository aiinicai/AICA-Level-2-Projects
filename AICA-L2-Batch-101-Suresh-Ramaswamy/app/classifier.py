"""GSTR-1 section classification from transaction facts (applied to extracted invoice lines).

Sections generated by this version: B2B, B2CL, B2CS, CDNR, CDNUR, EXP, NIL (Table 8), AT, ATADJ.
Amendments (9A / 9C / 10) cannot be derived from a single invoice line - they are entered through the
Master Template and never produced by this classifier.
"""
from decimal import Decimal
from typing import List

from .config import SECTIONS
from .gstin import is_valid_structure
from .models import Line, group_invoices, invoice_value
from .utils import D


def is_implemented(section: str) -> bool:
    return bool(SECTIONS.get(section, ("", False))[1])


def classify_line(l: Line, inv_total: Decimal, settings: dict):
    thr = D(settings.get("b2cl_threshold", "100000"))
    reg = bool(l.recipient_gstin) and is_valid_structure(l.recipient_gstin)
    it = (l.invoice_type or "").lower()
    sez_or_deemed = it.startswith("sez") or "deemed" in it
    export = it.startswith("export") or bool(l.export_type) or l.pos == "96"
    inter = bool(l.pos and l.supplier_gstin and l.pos != l.supplier_gstin[:2])
    if it == "advance":
        return "AT", "Advance received (Table 11A)"
    if it == "advance adjustment":
        return "ATADJ", "Advance adjusted (Table 11B)"
    if export:
        return ("CDNUR" if l.note_type in ("C", "D") else "EXP"), \
            ("Credit/debit note on an export" if l.note_type else "Export / supply to other country")
    nil = bool(l.taxable) and l.rate == 0 and l.tax_total == 0 and not sez_or_deemed
    if nil:
        return "NIL", "Zero-rate and zero-tax: reported in Table 8 (set the Nil / Exempt / Non-GST kind)"
    if l.note_type in ("C", "D"):
        if reg:
            return "CDNR", "Credit/debit note to a registered person"
        if inter and inv_total > thr:
            return "CDNUR", "Note to an unregistered person, inter-state and above the B2CL threshold"
        return "B2CS", "Note to an unregistered person is netted in B2CS (intra-state or below B2CL threshold)"
    if reg:
        return "B2B", "Registered recipient"
    if inter and inv_total > thr:
        return "B2CL", "Unregistered, inter-state, invoice value above threshold"
    return "B2CS", "Unregistered recipient"


def classify_all(lines: List[Line], settings: dict) -> None:
    """Assign l.section for every line (respecting manual overrides)."""
    for _, grp in group_invoices(lines).items():
        total = invoice_value(grp)
        for l in grp:
            if l.section_locked and l.section:
                continue
            l.section, _ = classify_line(l, total, settings)


def reason_for(l: Line, lines: List[Line], settings: dict) -> str:
    grp = [x for x in lines if x.key() == l.key()]
    return classify_line(l, invoice_value(grp), settings)[1]
