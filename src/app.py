@app.route('/api/import/upload', methods=['POST'])
def api_import_upload():
    if 'file' not in request.files:
        return jsonify({'status': 'error', 'message': 'No file uploaded'}), 400
    file = request.files['file']
    filename = file.filename
    ext = filename.split('.')[-1].lower()

    file_bytes = file.read()
    ledgers = []
    parser_used = ''

    try:
        if ext in ['xlsx', 'xls']:
            # ── Auto-detect TB format ─────────────────────────────────────────
            # Raw Tally TB (exported directly from Tally) has no explicit
            # "Parent Group" column.  It uses bold rows for group headers and
            # indentation for hierarchy.  convert_tally_excel() handles this
            # via openpyxl bold + indent detection, correctly skipping group
            # summary rows and only importing actual ledger rows.
            #
            # App-format files (generated by this tool's Tally Converter) DO
            # have a "Parent Tally Group" column.  parse_tally_excel() reads
            # that column directly and imports all data rows as ledgers (the
            # group separator rows starting with '—' are already skipped).
            import pandas as pd, io as _io
            try:
                df_peek = pd.read_excel(_io.BytesIO(file_bytes), nrows=0)
                cols_lower = [str(c).strip().lower() for c in df_peek.columns]
                has_group_col = any('group' in c or 'parent' in c for c in cols_lower)
            except Exception:
                has_group_col = False

            if has_group_col:
                # App-format or custom format with explicit group column
                ledgers = parse_tally_excel(file_bytes)
                parser_used = 'flat-format parser'
            else:
                # Raw Tally TB — use the converter that handles bold/indent groups
                ledgers, _stats, conv_errors = convert_tally_excel(file_bytes)
                parser_used = 'Tally-converter parser (bold/indent detection)'
                if not ledgers:
                    # Converter returned nothing — fall back to simple parser
                    ledgers = parse_tally_excel(file_bytes)
                    parser_used += ' → fallback flat-format parser'
                    if conv_errors:
                        import logging
                        logging.warning("Tally Converter errors: %s", conv_errors)

        elif ext == 'csv':
            ledgers = parse_tally_csv(file_bytes)
            parser_used = 'CSV parser'
        elif ext == 'xml':
            ledgers = parse_tally_xml(file_bytes)
            parser_used = 'XML parser'
        else:
            return jsonify({'status': 'error', 'message': f'Unsupported file format .{ext}'}), 400

        save_imported_ledgers(ledgers, source_filename=filename)
        mapped, reviews = execute_auto_mapping()

        return jsonify({
            'status': 'success',
            'message': (
                f'Successfully imported {len(ledgers)} ledgers from "{filename}" '
                f'using {parser_used}. '
                f'Auto-mapped {mapped} ledgers ({reviews} require CA review).'
            ),
            'count': len(ledgers)
        })
    except Exception as e:
        import traceback
        return jsonify({'status': 'error', 'message': f'Failed to parse file: {str(e)}', 'detail': traceback.format_exc()}), 500


