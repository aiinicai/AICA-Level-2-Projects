@app.route('/api/tally-converter/preview', methods=['POST'])
def api_tally_converter_preview():
    """
    POST a Tally TB Excel/CSV file; returns a JSON preview of parsed ledgers.
    Supports multipart file upload (field name: 'file').
    """
    if 'file' not in request.files:
        return jsonify({'status': 'error', 'message': 'No file uploaded'}), 400
    file = request.files['file']
    filename = file.filename or ''
    ext = filename.rsplit('.', 1)[-1].lower() if '.' in filename else ''
    file_bytes = file.read()

    if ext in ('xlsx', 'xls'):
        ledgers, stats, errors = convert_tally_excel(file_bytes)
    elif ext == 'csv':
        ledgers, stats, errors = convert_tally_csv(file_bytes)
    else:
        return jsonify({'status': 'error', 'message': f'Unsupported format .{ext}. Please upload .xlsx, .xls or .csv'}), 400

    if errors and not ledgers:
        return jsonify({'status': 'error', 'message': errors[0], 'errors': errors}), 422

    # Serialize a preview (max 200 rows for the table, full for download)
    preview = []
    for l in ledgers:
        opening = l['opening_dr'] - l['opening_cr']
        closing = l['closing_net']
        preview.append({
            'ledger_name'  : l['ledger_name'],
            'tally_group'  : l['tally_group'],
            'opening'      : f"{abs(opening):,.2f} {'Dr' if opening >= 0 else 'Cr'}",
            'debit'        : f"{l['debit']:,.2f}",
            'credit'       : f"{l['credit']:,.2f}",
            'closing'      : f"{abs(closing):,.2f} {'Dr' if closing >= 0 else 'Cr'}",
        })

    return jsonify({
        'status'  : 'success',
        'stats'   : stats,
        'errors'  : errors,
        'preview' : preview,
        'message' : f"Parsed {stats.get('total_ledgers',0)} ledgers from {filename} ({stats.get('groups_detected',0)} Tally groups detected)."
    })


