"""
Cents & Sensibility — Word Report Export
Assembles the full analysis into a formatted .docx for the audit file.
"""

import io
from . import branding
import re
from datetime import date

from docx import Document
from docx.shared import Pt, RGBColor, Inches
from docx.enum.text import WD_ALIGN_PARAGRAPH

NAVY = RGBColor(0x0F, 0x2A, 0x4A)
GOLD = RGBColor(0xB8, 0x8A, 0x2E)
GREY = RGBColor(0x55, 0x5A, 0x60)


def _h(doc, text, size=14, color=NAVY, space_before=10):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(space_before)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(size)
    r.font.color.rgb = color
    return p


def _table(doc, headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(h)
        run.bold = True
        run.font.size = Pt(9)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = "" if v is None else str(v)
            for p in cells[i].paragraphs:
                for r in p.runs:
                    r.font.size = Pt(9)
    return t


def _md_prose(doc, text):
    """Render narrative text, honouring **bold** spans."""
    for para in [p for p in text.split("\n") if p.strip()]:
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(6)
        for i, chunk in enumerate(re.split(r"\*\*(.+?)\*\*", para)):
            if not chunk:
                continue
            r = p.add_run(chunk)
            r.font.size = Pt(10.5)
            if i % 2 == 1:
                r.bold = True


def build_report(company: str, ratios_df, var_rows, z, m, health,
                 lens: dict, narrative_text: str, unit_label: str) -> bytes:
    doc = Document()

    # Cover block
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = title.add_run(branding.APP_NAME)
    r.bold = True; r.font.size = Pt(26); r.font.color.rgb = NAVY
    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = sub.add_run("Analytical Procedures & Financial Health Assessment")
    r.font.size = Pt(13); r.font.color.rgb = GOLD
    meta = doc.add_paragraph()
    meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = meta.add_run(f"{company}  |  Report date: {date.today():%d %B %Y}  |  Amounts: {unit_label}")
    r.font.size = Pt(10); r.font.color.rgb = GREY

    # 1. Health summary
    _h(doc, "1. Financial Health Summary")
    _table(doc, ["Measure", "Result", "Interpretation"], [
        ["Composite Financial Health Score", f"{health['score']} / 100", health["band"]],
        ["Altman Z'-Score (private-firm model)", z["score"], z["zone"]],
        ["Beneish M-Score (8-variable)", m["score"], m["verdict"]],
    ])
    doc.add_paragraph().add_run(
        "Component scores — " + "; ".join(f"{k}: {v}" for k, v in health["parts"].items())
    ).font.size = Pt(9)

    # 2. Ratios
    _h(doc, "2. Ratio Analysis")
    _table(doc, list(ratios_df.columns), ratios_df.values.tolist())

    # 3. SA 520 variance
    _h(doc, "3. SA 520 Variance Analysis (Expectation vs Actual)")
    _table(doc, ["Item", "Type", "Expectation (PY)", "Actual (CY)", "Change %", "Investigate"],
           [[r_["Item"], r_["Type"], r_["Prior Year (Expectation basis)"],
             r_["Current Year (Actual)"], r_["Change %"],
             "YES" if r_["Flag"] else "—"] for r_ in var_rows])

    # 4. Auditor's Lens
    _h(doc, "4. Auditor's Lens — Analytical Procedures Workpaper (Draft)")
    _table(doc, ["Area", "Expectation", "Actual", "Variance",
                 "Possible explanations", "Corroboration required"],
           [[w.get("area"), w.get("expectation"), w.get("actual"), w.get("variance"),
             w.get("possible_explanations"), w.get("corroboration_required")]
            for w in lens.get("workpaper", [])])

    _h(doc, "5. Going-Concern Indicator Assessment (SA 570)", size=13)
    _table(doc, ["Indicator", "Observation", "Assessment"],
           [[g.get("indicator"), g.get("observation"), g.get("assessment")]
            for g in lens.get("going_concern", [])])

    _h(doc, "6. Suggested Management Inquiries", size=13)
    for q in lens.get("inquiries", []):
        p = doc.add_paragraph(style="List Number")
        r = p.add_run(q); r.font.size = Pt(10)

    # 7. Narrative
    _h(doc, "7. AI-Drafted Financial Commentary")
    _md_prose(doc, narrative_text or "Narrative not generated in this session.")

    # Disclaimer
    _h(doc, "Important Note", size=11, color=GREY)
    p = doc.add_paragraph()
    r = p.add_run(
        f"This report is generated by {branding.APP_NAME} as draft analytical documentation. "
        "All AI-assisted content herein requires review, validation and professional "
        "judgement by the engagement partner before reliance. Forensic scores "
        "(Altman Z', Beneish M) are screening indicators, not conclusions."
    )
    r.font.size = Pt(9); r.italic = True; r.font.color.rgb = GREY

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
