def offline_assumption_engine(data):
    """Deterministic offline analytics. No model/API call."""
    hist = data["historical"]
    sales = [num(x) for x in hist["sales"]]
    ebitda = [num(x) for x in hist["ebitda"]]
    da = [num(x) for x in hist["da"]]
    capex = [num(x) for x in hist["capex"]]
    nwc = [num(x) for x in hist["nwc"]]

    positive_sales = [(i,v) for i,v in enumerate(sales) if v > 0]
    cagr = 0.08
    if len(positive_sales) >= 2:
        i0,v0 = positive_sales[0]
        i1,v1 = positive_sales[-1]
        yrs = max(1, i1-i0)
        cagr = (v1/v0)**(1/yrs)-1 if v0 > 0 and v1 > 0 else 0.08
    cagr = min(max(cagr, -0.05), 0.25)

    margins = [safe_div(e,s) for e,s in zip(ebitda,sales) if s>0 and e!=0]
    margin = statistics.median(margins[-3:]) if margins else 0.18
    margin = min(max(margin, 0.05), 0.40)

    da_ratios = [safe_div(d,s) for d,s in zip(da,sales) if s>0 and d>=0]
    capex_ratios = [safe_div(c,s) for c,s in zip(capex,sales) if s>0 and c>=0]
    da_pct = statistics.median(da_ratios[-3:]) if da_ratios else 0.03
    capex_pct = statistics.median(capex_ratios[-3:]) if capex_ratios else max(0.04, da_pct*1.15)

    growth = []
    start = cagr
    terminal_operating_growth = min(max(0.06, cagr*0.55), 0.10)
    for i in range(5):
        growth.append(start + (terminal_operating_growth-start)*(i/4))
    margin_target = min(0.40, max(0.05, margin + 0.01))
    margins_fcst = [margin + (margin_target-margin)*(i/4) for i in range(5)]

    # NWC intensity based on ending NWC/sales; use conservative fraction of incremental revenue.
    nwc_ratios = [safe_div(n,s) for n,s in zip(nwc,sales) if s>0 and n!=0]
    nwc_inc = statistics.median(nwc_ratios[-3:]) if nwc_ratios else 0.08
    nwc_inc = min(max(nwc_inc, 0.02), 0.25)

    return {
        "growth": [round(x*100,2) for x in growth],
        "ebitda_margin": [round(x*100,2) for x in margins_fcst],
        "tax_rate": 25.0,
        "da_pct": round(da_pct*100,2),
        "capex_pct": round(capex_pct*100,2),
        "nwc_increment_pct": round(nwc_inc*100,2),
        "terminal_growth": 5.0,
        "rationale": (
            f"Offline engine used historical sales CAGR of {cagr*100:.2f}%, "
            f"median EBITDA margin of {margin*100:.2f}%, and normalized reinvestment ratios. "
            "Forecast growth is mean-reverting rather than a straight extrapolation."
        )
    }

def _extract_json_object(text):
    text = text.strip()
    text = re.sub(r"^```(?:json)?\s*", "", text, flags=re.I)
    text = re.sub(r"\s*```$", "", text)
    m = re.search(r"\{.*\}", text, re.S)
    if not m:
        raise ValueError("AI response did not contain a JSON object.")
    return json.loads(m.group(0))

