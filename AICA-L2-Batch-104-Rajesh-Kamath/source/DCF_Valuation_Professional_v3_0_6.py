    def generate_ai_assumptions(self):
        provider=self.ai_provider.get()
        model=self.ai_model.get().strip() or provider_default_model(provider)
        self.ai_model.set(model)
        if provider.startswith(("OpenAI","Gemini")):
            ok=messagebox.askyesno(
                "Online AI Privacy Notice",
                "This will send the extracted financial data and document text shown by this application to the selected online AI provider. The original file itself is not uploaded by this function.\n\nContinue?"
            )
            if not ok:return
        if provider.startswith("Ollama"):
            ok,msg,models=ollama_health()
            if not ok:
                messagebox.showwarning("Ollama Local AI",msg)
                return
            if not models:
                messagebox.showwarning("Ollama Local AI",f"Ollama is running, but no local model is installed.\n\nRun:\nollama pull {model or 'gemma3'}")
                return

        progress=tk.Toplevel(self)
        progress.title("Generating AI Assumptions")
        progress.geometry("520x200")
        progress.resizable(False,False)
        progress.transient(self); progress.grab_set()
        ttk.Label(progress,text="🧠 AI analysis in progress",font=("Segoe UI",14,"bold")).pack(pady=(22,8))
        ttk.Label(progress,text=f"Provider: {provider}\nModel: {model}\n\nLocal Ollama analysis may take several minutes on the first run while the model loads into memory.",justify="center",wraplength=470).pack(padx=20)
        pb=ttk.Progressbar(progress,mode="indeterminate",length=400); pb.pack(pady=16); pb.start(12)
        self.status.set(f"Generating assumptions with {provider}...")
        self.update_idletasks()
        holder={"result":None,"error":None}
        data_snapshot=self.gather()
        preview_snapshot=self.imported_preview
        api_key_snapshot=self.ai_key.get().strip()

        def worker():
            try:
                holder["result"]=ai_assumptions(provider,model,api_key_snapshot,data_snapshot,preview_snapshot)
            except Exception as e:
                holder["error"]=e
            self.after(100,finish)

        def finish():
            try:
                pb.stop(); progress.grab_release(); progress.destroy()
            except Exception:
                pass
            if holder["error"] is not None:
                friendly=friendly_ai_error(provider,holder["error"])
                self._log_import("AI ERROR: "+friendly.replace("\n"," "))
                messagebox.showerror("AI Assumptions",friendly)
                self.status.set("AI assumption generation failed.")
                return
            try:
                self._apply_ai_result(holder["result"])
                messagebox.showinfo("AI Assumptions","AI-generated assumptions were applied. Review all assumptions before using the valuation.")
                self.status.set("AI assumptions generated.")
            except Exception as e:
                messagebox.showerror("AI Assumptions",str(e))
                self.status.set("AI assumption generation failed.")

        threading.Thread(target=worker,daemon=True).start()


