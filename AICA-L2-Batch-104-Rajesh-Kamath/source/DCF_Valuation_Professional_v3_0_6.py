def ollama_health():
    """Return (ok, message, installed_models)."""
    try:
        req = urllib.request.Request("http://localhost:11434/api/tags", method="GET")
        with urllib.request.urlopen(req, timeout=3) as resp:
            obj = json.loads(resp.read().decode("utf-8"))
        models = []
        for m in obj.get("models", []):
            name = m.get("name") or m.get("model")
            if name:
                models.append(name)
        return True, "Ollama is running locally.", models
    except urllib.error.URLError as e:
        reason = getattr(e, "reason", e)
        # Friendly distinction for connection refused
        if isinstance(reason, ConnectionRefusedError) or "10061" in str(reason) or "refused" in str(reason).lower():
            exe = shutil.which("ollama")
            if exe:
                return False, "Ollama is installed but its local service is not running. Start Ollama, or run: ollama serve", []
            return False, "Ollama is not reachable. Install Ollama for Windows, start it, then download a model such as: ollama pull gemma3", []
        return False, f"Ollama connection failed: {reason}", []
    except Exception as e:
        return False, f"Ollama check failed: {e}", []

def try_start_ollama():
    """Best-effort start of local Ollama server if executable is available."""
    exe = shutil.which("ollama")
    if not exe:
        return False, "Ollama executable was not found in PATH."
    try:
        # Avoid console popup on Windows where possible.
        creationflags = 0
        if os.name == "nt" and hasattr(subprocess, "CREATE_NO_WINDOW"):
            creationflags = subprocess.CREATE_NO_WINDOW
        subprocess.Popen(
            [exe, "serve"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            stdin=subprocess.DEVNULL,
            creationflags=creationflags
        )
        import time
        for _ in range(10):
            time.sleep(0.5)
            ok, msg, models = ollama_health()
            if ok:
                return True, msg
        return False, "Ollama was started but the local API did not become ready in time."
    except Exception as e:
        return False, f"Could not start Ollama automatically: {e}"

