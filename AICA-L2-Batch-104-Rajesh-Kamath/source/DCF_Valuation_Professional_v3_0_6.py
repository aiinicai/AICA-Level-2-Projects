def _verify_activation_token_detailed(token_text):
    """
    Returns (ok, reason, payload_obj).
    This gives precise diagnostics without exposing the private signing key.
    """
    try:
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    except Exception as e:
        return False, f"Cryptography library unavailable: {e}", None

    try:
        token_text = (token_text or "").strip()
        # Remove accidental spaces/newlines copied from wrapped text boxes.
        token_text = "".join(token_text.split())
        if not token_text:
            return False, "No reuse key was entered.", None
        if "." not in token_text:
            return False, "Malformed key: separator is missing.", None

        payload_b64, sig_b64 = token_text.split(".", 1)
        try:
            payload = base64.urlsafe_b64decode(payload_b64 + "=" * (-len(payload_b64) % 4))
            signature = base64.urlsafe_b64decode(sig_b64 + "=" * (-len(sig_b64) % 4))
        except Exception:
            return False, "Malformed key: Base64 decoding failed.", None

        try:
            pub = Ed25519PublicKey.from_public_bytes(base64.b64decode(LICENSE_PUBLIC_KEY_B64))
            pub.verify(signature, payload)
        except Exception:
            return False, "Signature verification failed. This key was not generated by the matching v3.0.6 private generator.", None

        try:
            obj = json.loads(payload.decode("utf-8"))
        except Exception:
            return False, "Signed payload is not valid JSON.", None

        if obj.get("product") != "DCFVP306":
            return False, f"Wrong product/version token: {obj.get('product')!r}. Expected DCFVP306.", obj

        signed_machine = str(obj.get("machine", "")).strip().upper()
        current_machine = machine_code().strip().upper()
        if signed_machine != current_machine:
            return False, f"Machine-code mismatch. Key is for {signed_machine}; this PC is {current_machine}.", obj

        return True, "Signature, product and machine code are valid.", obj
    except Exception as e:
        return False, f"Unexpected verification error: {e}", None


