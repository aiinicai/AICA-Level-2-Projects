def num(v, default=0.0):
    try:
        if v is None:
            return default
        s = str(v).strip().replace(",", "").replace("₹", "").replace("%", "")
        if not s:
            return default
        return float(s)
    except Exception:
        return default

def pct(v, default=0.0):
    x = num(v, default)
    return x / 100.0

