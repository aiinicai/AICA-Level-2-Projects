def ai_assumptions(provider, model, api_key, data, preview=""):
    prompt = build_ai_prompt(data, preview)
    provider = provider.lower()
    if provider.startswith("ollama"):
        ok, health_msg, installed = ollama_health()
        if not ok:
            raise ConnectionError(health_msg)
        chosen = model or "gemma3"
        # Accept either exact model or base model before colon.
        if installed and not any(chosen == m or m.startswith(chosen + ":") or chosen.startswith(m + ":") for m in installed):
            raise ValueError(
                f"Ollama is running, but model '{chosen}' is not installed. "
                f"Installed models: {', '.join(installed) if installed else 'none'}. "
                f"Run: ollama pull {chosen}"
            )
        payload = json.dumps({
            "model": chosen,
            "messages": [{"role":"user","content":prompt}],
            "stream": False,
            "format": "json",
            "keep_alive": "10m",
            "options": {"temperature": 0.2, "num_ctx": 4096}
        }).encode("utf-8")
        req = urllib.request.Request(
            "http://localhost:11434/api/chat",
            data=payload,
            headers={"Content-Type":"application/json"},
            method="POST"
        )
        with urllib.request.urlopen(req, timeout=600) as resp:
            obj = json.loads(resp.read().decode("utf-8"))
        return _extract_json_object(obj["message"]["content"])

    if provider.startswith("openai"):
        key = api_key or os.environ.get("OPENAI_API_KEY")
        if not key:
            raise ValueError("No OpenAI API key supplied.")
        chosen = model or "gpt-5.6-terra"
        payload = json.dumps({
            "model": chosen,
            "input": prompt
        }).encode("utf-8")
        req = urllib.request.Request(
            "https://api.openai.com/v1/responses",
            data=payload,
            headers={
                "Content-Type": "application/json",
                "Authorization": f"Bearer {key}"
            },
            method="POST"
        )
        try:
            with urllib.request.urlopen(req, timeout=180) as resp:
                obj = json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as e:
            body = e.read().decode("utf-8", "ignore")
            raise RuntimeError(f"OpenAI HTTP {e.code}: {body[:500]}")
        text = ""
        if isinstance(obj, dict):
            if obj.get("output_text"):
                text = obj["output_text"]
            else:
                # Responses API structured output traversal
                for item in obj.get("output", []):
                    for content in item.get("content", []):
                        if isinstance(content, dict) and content.get("text"):
                            text += content.get("text", "")
        if not text:
            raise ValueError("OpenAI returned no text response.")
        return _extract_json_object(text)

    if provider.startswith("gemini"):
        key = api_key or os.environ.get("GEMINI_API_KEY")
        if not key:
            raise ValueError("No Gemini API key supplied.")
        chosen = model or "gemini-3.7-flash"
        url = (
            "https://generativelanguage.googleapis.com/v1beta/models/"
            + urllib.parse.quote(chosen, safe="")
            + ":generateContent?key="
            + urllib.parse.quote(key, safe="")
        )
        payload = json.dumps({
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {"responseMimeType": "application/json"}
        }).encode("utf-8")
        req = urllib.request.Request(
            url,
            data=payload,
            headers={"Content-Type": "application/json"},
            method="POST"
        )
        try:
            with urllib.request.urlopen(req, timeout=180) as resp:
                obj = json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as e:
            body = e.read().decode("utf-8", "ignore")
            raise RuntimeError(f"Gemini HTTP {e.code}: {body[:500]}")
        try:
            text = obj["candidates"][0]["content"]["parts"][0]["text"]
        except Exception:
            raise ValueError("Gemini returned no text response.")
        return _extract_json_object(text)

    raise ValueError("Unknown AI provider.")

