    def load_data(self,data):
        imp=data.get("import_info",{})
        self.imported_file=imp.get("source_file",""); self.imported_preview=imp.get("preview_excerpt","")
        if hasattr(self,"import_file_var"): self.import_file_var.set(self.imported_file)
        c=data.get("company",{})
        for key,field in [("company_name","name"),("industry","industry"),("valuation_date","valuation_date"),("shares","shares"),("currency","currency")]:
            if field in c:self.entries[key].set(c[field])
        self.mode.set(c.get("mode","Listed"))
        for k,arr in data.get("historical",{}).items():
            if k in self.hist_entries:
                for i,v in enumerate(arr[:5]): self.hist_entries[k][i].set(v)
        for k,arr in data.get("forecast",{}).items():
            if k in self.fcst_entries:
                for i,v in enumerate(arr[:5]): self.fcst_entries[k][i].set(v)
        for section in ["assumptions","capital","bridge"]:
            for k,v in data.get(section,{}).items():
                if k in self.entries:self.entries[k].set(v)
        for i in self.comp_tree.get_children(): self.comp_tree.delete(i)
        for c in data.get("comparables",[]): self.comp_tree.insert("","end",values=(c.get("company",""),c.get("beta",""),c.get("de",""),c.get("tax","")))
        for n,d in data.get("scenarios",{}).items():
            if n in self.scenario_vars:
                for k,v in d.items():
                    if k in self.scenario_vars[n]: self.scenario_vars[n][k].set(v)

    def calculate(self):
        try:
            data=self.gather()
            if num(data["historical"]["sales"][-1])<=0:
                raise ValueError("Please enter positive FY0 revenue in Historical Financials.")
            self.result=DCFEngine.calculate(data)
            r=self.result
            self.kpis["cost_equity"].set(fmt_pct(r.cost_equity)); self.kpis["wacc"].set(fmt_pct(r.wacc))
            self.kpis["ev"].set(fmt_money(r.enterprise_value)); self.kpis["eq"].set(fmt_money(r.equity_value))
            self.kpis["vps"].set(fmt_money(r.value_per_share)); self.kpis["beta"].set(f"{r.bottom_up_beta:.3f}" if r.bottom_up_beta else "-")
            for x in self.fcff_tree.get_children(): self.fcff_tree.delete(x)
            for i,y in enumerate(YEARS_FCST):
                self.fcff_tree.insert("","end",values=(y,fmt_money(r.forecast_sales[i]),fmt_money(r.forecast_ebitda[i]),fmt_money(r.fcff[i]),fmt_money(r.pv_fcff[i])))
            for x in self.scenario_tree.get_children(): self.scenario_tree.delete(x)
            for name,val in r.scenario_values.items():
                self.scenario_tree.insert("","end",values=(name,fmt_money(val) if val is not None else "N/M"))
            self._render_sensitivity()
            self.nb.select(self.tabs["Results"])
            self.status.set(f"Calculated successfully. Intrinsic value: {fmt_money(r.value_per_share)}")
        except Exception as e:
            messagebox.showerror("Calculation Error",str(e))
            self.status.set("Calculation failed.")

    def _render_sensitivity(self):
        r=self.result
        if not r:return
        cols=["wacc"]+[f"g{i}" for i in range(5)]
        self.sensitivity_tree["columns"]=cols
        self.sensitivity_tree.heading("wacc",text="WACC \\ g"); self.sensitivity_tree.column("wacc",width=120,anchor="center")
        gkeys=list(next(iter(r.sensitivity.values())).keys())
        for i,g in enumerate(gkeys):
            self.sensitivity_tree.heading(f"g{i}",text=fmt_pct(g)); self.sensitivity_tree.column(f"g{i}",width=135,anchor="e")
        for x in self.sensitivity_tree.get_children():self.sensitivity_tree.delete(x)
        for w,row in r.sensitivity.items():
            vals=[fmt_pct(w)]+[fmt_money(row[g]) if row[g] is not None else "N/M" for g in gkeys]
            self.sensitivity_tree.insert("","end",values=vals)

