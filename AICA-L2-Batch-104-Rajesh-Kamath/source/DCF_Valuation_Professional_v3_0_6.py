class DCFEngine:
    @staticmethod
    def bottom_up_beta(comps):
        unlevered = []
        for c in comps:
            beta_l = num(c.get("beta"))
            de = num(c.get("de"))
            tax = pct(c.get("tax"))
            if beta_l > 0:
                denom = 1 + (1-tax) * de
                if denom > 0:
                    unlevered.append(beta_l / denom)
        return sum(unlevered) / len(unlevered) if unlevered else 0.0

    @staticmethod
    def calculate(data):
        hist_sales = [num(x) for x in data["historical"]["sales"]]
        base_sales = hist_sales[-1]
        growth = [pct(x) for x in data["forecast"]["growth"]]
        margins = [pct(x) for x in data["forecast"]["ebitda_margin"]]
        tax = pct(data["assumptions"]["tax_rate"])
        da_pct = pct(data["assumptions"]["da_pct"])
        capex_pct = pct(data["assumptions"]["capex_pct"])
        nwc_pct = pct(data["assumptions"]["nwc_increment_pct"])
        terminal_g = pct(data["assumptions"]["terminal_growth"])

        mode = data["company"]["mode"]
        comps = data.get("comparables", [])
        bottom_beta = DCFEngine.bottom_up_beta(comps)
        if mode == "Unlisted":
            target_de = num(data["capital"]["target_de"])
            beta = bottom_beta * (1 + (1-tax) * target_de) if bottom_beta > 0 else num(data["capital"]["beta"])
        else:
            beta = num(data["capital"]["beta"])

        rf = pct(data["capital"]["risk_free"])
        erp = pct(data["capital"]["erp"])
        csrp = pct(data["capital"]["csrp"])
        cost_equity = rf + beta * erp + csrp
        pre_tax_kd = pct(data["capital"]["cost_debt"])
        after_tax_kd = pre_tax_kd * (1-tax)

        debt_weight = pct(data["capital"]["debt_weight"])
        debt_weight = min(max(debt_weight, 0), 1)
        equity_weight = 1 - debt_weight
        wacc = cost_equity * equity_weight + after_tax_kd * debt_weight

        if wacc <= terminal_g:
            raise ValueError("WACC must be greater than terminal growth rate.")

        sales, ebitda, ebit, nopat, da, capex, d_nwc, fcff = [], [], [], [], [], [], [], []
        prev_sales = base_sales
        for i in range(5):
            s = prev_sales * (1 + growth[i])
            e = s * margins[i]
            dep = s * da_pct
            eb = e - dep
            npat = eb * (1-tax)
            cx = s * capex_pct
            dn = max(0.0, (s - prev_sales) * nwc_pct)
            f = npat + dep - cx - dn
            sales.append(s); ebitda.append(e); da.append(dep); ebit.append(eb)
            nopat.append(npat); capex.append(cx); d_nwc.append(dn); fcff.append(f)
            prev_sales = s

        dfs = [1 / ((1+wacc)**(i+1)) for i in range(5)]
        pv_fcff = [fcff[i]*dfs[i] for i in range(5)]
        tv = fcff[-1] * (1+terminal_g) / (wacc-terminal_g)
        pv_tv = tv * dfs[-1]
        ev = sum(pv_fcff) + pv_tv

        cash = num(data["bridge"]["cash"])
        investments = num(data["bridge"]["investments"])
        debt = num(data["bridge"]["debt"])
        minorities = num(data["bridge"]["minority_interest"])
        other_claims = num(data["bridge"]["other_claims"])
        other_assets = num(data["bridge"]["other_assets"])
        eq = ev - debt - minorities - other_claims + cash + investments + other_assets
        shares = num(data["company"]["shares"])
        value_per_share = eq / shares if shares > 0 else eq

        sensitivity = {}
        wacc_offsets = [-0.02, -0.01, 0, 0.01, 0.02]
        g_offsets = [-0.01, -0.005, 0, 0.005, 0.01]
        for wo in wacc_offsets:
            rw = wacc + wo
            row = {}
            for go in g_offsets:
                rg = terminal_g + go
                if rw <= rg or rw <= 0:
                    val = None
                else:
                    t = fcff[-1]*(1+rg)/(rw-rg)
                    df = [1/((1+rw)**(i+1)) for i in range(5)]
                    re = sum(fcff[i]*df[i] for i in range(5)) + t*df[-1]
                    req = re - debt - minorities - other_claims + cash + investments + other_assets
                    val = req/shares if shares > 0 else req
                row[round(rg,6)] = val
            sensitivity[round(rw,6)] = row

        scenarios = {}
        scenario_inputs = data.get("scenarios", {})
        for name in ["Bear","Base","Bull"]:
            sc = scenario_inputs.get(name, {})
            g_adj = pct(sc.get("growth_adj", 0))
            m_adj = pct(sc.get("margin_adj", 0))
            w_adj = pct(sc.get("wacc_adj", 0))
            tg_adj = pct(sc.get("terminal_growth_adj", 0))
            rw = wacc + w_adj
            rg = terminal_g + tg_adj
            p_sales = base_sales
            s_fcff = []
            for i in range(5):
                gs = max(-0.99, growth[i] + g_adj)
                ms = max(0, margins[i] + m_adj)
                ss = p_sales*(1+gs)
                ee = ss*ms
                dd = ss*da_pct
                eb = ee-dd
                nn = eb*(1-tax)
                cc = ss*capex_pct
                dn = max(0, (ss-p_sales)*nwc_pct)
                s_fcff.append(nn+dd-cc-dn)
                p_sales = ss
            if rw <= rg:
                scenarios[name] = None
            else:
                df = [1/((1+rw)**(i+1)) for i in range(5)]
                tvs = s_fcff[-1]*(1+rg)/(rw-rg)
                sev = sum(s_fcff[i]*df[i] for i in range(5)) + tvs*df[-1]
                seq = sev - debt - minorities - other_claims + cash + investments + other_assets
                scenarios[name] = seq/shares if shares > 0 else seq

        return ValuationResult(
            forecast_sales=sales, forecast_ebitda=ebitda, forecast_ebit=ebit,
            nopat=nopat, da=da, capex=capex, delta_nwc=d_nwc, fcff=fcff,
            discount_factors=dfs, pv_fcff=pv_fcff, cost_equity=cost_equity,
            after_tax_cost_debt=after_tax_kd, wacc=wacc, terminal_growth=terminal_g,
            terminal_value=tv, pv_terminal_value=pv_tv, enterprise_value=ev,
            equity_value=eq, value_per_share=value_per_share,
            bottom_up_beta=bottom_beta, scenario_values=scenarios,
            sensitivity=sensitivity
        )

