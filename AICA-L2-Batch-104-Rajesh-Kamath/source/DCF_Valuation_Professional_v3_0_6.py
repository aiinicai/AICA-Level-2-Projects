    def review_import_mapping(self,mapped,provenance,confidence,warnings):
        win=tk.Toplevel(self); win.title("Review Imported Financial Mapping"); win.geometry("1180x560")
        win.transient(self); win.grab_set()
        ttk.Label(win,text="Review Imported Financials Before Posting",font=("Segoe UI",14,"bold")).pack(pady=(12,4))
        ttk.Label(win,text="Double-click any row to toggle YES/NO. Rejected mappings default to NO.").pack()
        cols=("use","metric","confidence","fy4","fy3","fy2","fy1","fy0","source")
        tree=ttk.Treeview(win,columns=cols,show="headings",height=14)
        heads={"use":"Use","metric":"Metric","confidence":"Confidence","fy4":"FY-4","fy3":"FY-3","fy2":"FY-2","fy1":"FY-1","fy0":"FY0","source":"Source"}
        widths={"use":55,"metric":120,"confidence":80,"fy4":90,"fy3":90,"fy2":90,"fy1":90,"fy0":90,"source":390}
        for c in cols:
            tree.heading(c,text=heads[c]); tree.column(c,width=widths[c],anchor="w" if c=="source" else "center")
        tree.pack(fill="both",expand=True,padx=10,pady=8)
        for m in ["sales","ebitda","da","ebit","capex","nwc"]:
            if m in mapped:
                conf=confidence.get(m,"Low"); use="NO" if conf=="Reject" else "YES"
                tree.insert("","end",values=(use,m,conf,*[f"{v:,.2f}" for v in mapped[m]],provenance.get(m,"")))
        def toggle(event=None):
            sel=tree.selection()
            if not sel:return
            iid=sel[0]; vals=list(tree.item(iid,"values")); vals[0]="NO" if vals[0]=="YES" else "YES"; tree.item(iid,values=vals)
        tree.bind("<Double-1>",toggle)
        warn="\n".join("• "+w for w in warnings) if warnings else "No critical warnings."
        ttk.Label(win,text=warn,foreground="#8B0000",wraplength=1120,justify="left").pack(fill="x",padx=12,pady=6)
        result={"accepted":None}
        def accept():
            accepted={}
            for iid in tree.get_children():
                vals=tree.item(iid,"values")
                if vals[0]=="YES":accepted[vals[1]]=mapped[vals[1]]
            result["accepted"]=accepted; win.destroy()
        bf=ttk.Frame(win); bf.pack(pady=8)
        ttk.Button(bf,text="Accept Selected",command=accept).pack(side="left",padx=5)
        ttk.Button(bf,text="Cancel Import",command=win.destroy).pack(side="left",padx=5)
        self.wait_window(win)
        return result["accepted"]

    def import_financial_file(self):
        path=filedialog.askopenfilename(title="Select financial statements",
            filetypes=[("Financial files","*.xlsx *.xlsm *.pdf"),("Excel","*.xlsx *.xlsm"),("PDF","*.pdf")])
        if not path:return
        self.import_file_var.set(path); self.imported_file=path; self._log_import(f"Importing: {path}")
        try:
            ext=Path(path).suffix.lower()
            if ext in (".xlsx",".xlsm"):
                mapped,preview,provenance,warnings,confidence=extract_financials_from_excel(path)
            elif ext==".pdf":
                mapped,preview,provenance,warnings,confidence=extract_financials_from_pdf(path)
            else:raise ValueError("Unsupported file format.")
            self.imported_preview=preview
            if not mapped:
                self._log_import("No reliable financial metrics found."); return
            self._log_import("Candidate financial mappings:")
            for k,v in mapped.items():
                self._log_import(f"  {k}: {v}")
                self._log_import(f"     confidence: {confidence.get(k,'Low')}")
                self._log_import(f"     source: {provenance.get(k,'unknown')}")
            for w in warnings:self._log_import("WARNING: "+w)
            accepted=self.review_import_mapping(mapped,provenance,confidence,warnings)
            if accepted is None:
                self._log_import("Import cancelled by user."); return
            for metric,vals in accepted.items():
                if metric in self.hist_entries:
                    for i,v in enumerate(vals[-5:]):self.hist_entries[metric][i].set(f"{v:.2f}")
            self._log_import("Accepted mappings posted to Historical: "+", ".join(accepted.keys()))
            self.nb.select(self.tabs["Historical"])
        except Exception as e:
            self._log_import(f"ERROR: {e}"); messagebox.showerror("Import Financials",str(e))


    def _apply_ai_result(self,res):
        required=["growth","ebitda_margin","tax_rate","da_pct","capex_pct","nwc_increment_pct","terminal_growth"]
        missing=[x for x in required if x not in res]
        if missing: raise ValueError("AI response missing: "+", ".join(missing))
        for i,v in enumerate(res["growth"][:5]): self.fcst_entries["growth"][i].set(str(round(num(v),2)))
        for i,v in enumerate(res["ebitda_margin"][:5]): self.fcst_entries["ebitda_margin"][i].set(str(round(num(v),2)))
        for k in ["tax_rate","da_pct","capex_pct","nwc_increment_pct","terminal_growth"]:
            self.entries[k].set(str(round(num(res[k]),2)))
        self._log_import("Assumptions applied:")
        self._log_import(json.dumps(res,indent=2))
        self.nb.select(self.tabs["Forecast"])

