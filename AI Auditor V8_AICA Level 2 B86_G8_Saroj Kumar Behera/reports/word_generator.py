    def _build_audit_verification_section(self):
        h = self.doc.add_heading("7. Audit Verification Requirements & Corroborative Evidence", level=1)
        h.runs[0].font.name = 'Segoe UI'
        h.runs[0].font.color.rgb = RGBColor(26, 54, 93)

        p = self.doc.add_paragraph()
        p.add_run(
            "In accordance with Standards on Auditing (SA 500 / SA 520), the following specific documents "
            "and schedules are required to obtain sufficient and appropriate audit evidence for material movements."
        )

        # Collect flat list of audit requirements
        flat_reqs = []
        for v in self.model.variations:
            for item in v["audit_verification"]:
                flat_reqs.append((v["particulars"], item["doc"], item["why"]))

        if not flat_reqs:
            return

        table = self.doc.add_table(rows=1 + len(flat_reqs[:25]), cols=3)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        headers = ["Financial Statement Area", "Required Audit Document / Evidence", "WHY Document is Required (Audit Purpose)"]

        for c_idx, head in enumerate(headers):
            cell = table.cell(0, c_idx)
            self._set_cell_background(cell, "1A365D")
            p = cell.paragraphs[0]
            r = p.add_run(head)
            r.font.name = 'Segoe UI'
            r.font.bold = True
            r.font.size = Pt(8.5)
            r.font.color.rgb = RGBColor(255, 255, 255)

        for r_idx, (part, doc_name, why_txt) in enumerate(flat_reqs[:25], 1):
            c0 = table.cell(r_idx, 0)
            c1 = table.cell(r_idx, 1)
            c2 = table.cell(r_idx, 2)

            c0.paragraphs[0].add_run(part).font.size = Pt(8)
            c0.paragraphs[0].runs[0].font.bold = True
            c1.paragraphs[0].add_run(doc_name).font.size = Pt(8)
            c2.paragraphs[0].add_run(why_txt).font.size = Pt(8)

            for c in [c0, c1, c2]:
                self._set_cell_background(c, "F7FAFC" if r_idx % 2 == 0 else "FFFFFF")
                self._set_cell_margins(c, top=40, bottom=40)

        self.doc.add_paragraph().paragraph_format.space_after = Pt(12)

    def _build_risk_areas_section(self):
        h = self.doc.add_heading("8. Potential Risk & Attention Areas Matrix", level=1)
        h.runs[0].font.name = 'Segoe UI'
        h.runs[0].font.color.rgb = RGBColor(26, 54, 93)

