"""
E-way bill analysis and reconciliation.

Reads the e-way-bill export the user downloads from the EWB portal
(ewaybillgst.gov.in -> Reports -> EWB generated by me / detailed), in Excel or
CSV, normalises its columns (headers vary by report), and produces:

  * a clean line-level table
  * customer-wise (recipient) analysis
  * document-type and supply-type analysis
  * status (active / cancelled) and HSN and transporter analysis
  * month-wise outward value, for reconciliation against GSTR-1

Column matching is fuzzy so it works across the portal's report variants.
Pure pandas - no network.
"""
from __future__ import annotations

import re
from datetime import date

import pandas as pd

# canonical field -> list of header keywords (lower-case, spaces/punctuation ignored)
_FIELDS = {
    "ewb_no": ["ewaybillno", "ewbno", "ewaybillnumber", "ewbnumber"],
    "ewb_date": ["ewaybilldate", "ewbdate", "generateddate", "dateofgeneration"],
    "doc_no": ["docno", "documentno", "invoiceno", "invno"],
    "doc_date": ["docdate", "documentdate", "invoicedate", "invdate"],
    "doc_type": ["doctype", "documenttype"],
    "supply_type": ["supplytype"],                 # Outward / Inward
    "txn_type": ["transactiontype", "txntype", "subsupplytype", "subtype"],
    "status": ["status"],
    "cat": ["category"],
    "party_gstin": ["gstinofrecipient", "recipientgstin", "gstinofsupplier", "suppliergstin",
                    "otherpartygstin", "ctin", "gstin"],
    "party_name": ["recipientname", "suppliername", "tradename", "otherpartyname", "legalname", "name"],
    "place": ["placetostate", "tostate", "otherpartystate", "stateofrecipient", "pos", "placeofsupply"],
    "value": ["assessablevalue", "taxablevalue", "taxableamount", "totalinvvalue", "totalinvoicevalue",
              "totalvalue", "invoicevalue", "value"],
    "igst": ["igstamount", "igstamt", "igst"],
    "cgst": ["cgstamount", "cgstamt", "cgst"],
    "sgst": ["sgstamount", "sgstamt", "sgst"],
    "cess": ["cessamount", "cessamt", "cess"],
    "hsn": ["hsncode", "hsn"],
    "transporter": ["transportername", "transporter", "transporterid", "transgstin"],
    "distance": ["distance", "approxdistance", "distancekm"],
    "mode": ["mode", "transmode", "transportationmode"],
    "vehicle": ["vehicleno", "vehiclenumber"],
}

DOC_TYPES = {"INV": "Tax Invoice", "BIL": "Bill of Supply", "BOE": "Bill of Entry",
             "CHL": "Delivery Challan", "OTH": "Others", "CRN": "Credit Note", "DBN": "Debit Note"}


def _norm(s):
    return re.sub(r"[^a-z0-9]", "", str(s).lower())


def _map_columns(df):
    norm = {_norm(c): c for c in df.columns}
    mapping = {}
    for field, keys in _FIELDS.items():
        for k in keys:
            # exact normalised match first
            if k in norm:
                mapping[field] = norm[k]
                break
        if field in mapping:
            continue
        for k in keys:                       # then substring
            hit = next((orig for n, orig in norm.items() if k in n), None)
            if hit:
                mapping[field] = hit
                break
    return mapping


def _enum(s):
    return pd.to_numeric(
        s.astype(str).str.replace(r"[,\s₹]", "", regex=True).replace({"": "0", "nan": "0", "-": "0"}),
        errors="coerce").fillna(0.0)


def _parse_date(s):
    for fmt in ("%d/%m/%Y", "%d-%m-%Y", "%Y-%m-%d", "%d/%m/%Y %H:%M:%S", "%d-%b-%Y", "%d/%m/%y"):
        try:
            return pd.to_datetime(s, format=fmt, errors="raise")
        except Exception:
            continue
    return pd.to_datetime(s, errors="coerce", dayfirst=True)


def _as_headerless(df):
    """Return a frame with integer columns and the header text kept as a DATA row, so the
    header-row finder in load_export works the same whatever the reader did with columns."""
    df = df.astype(str)
    if list(df.columns) == list(range(df.shape[1])):
        return df.reset_index(drop=True)
    cols = ["" if str(c).startswith("Unnamed") else str(c) for c in df.columns]
    top = pd.DataFrame([cols])
    body = pd.DataFrame(df.values)
    return pd.concat([top, body], ignore_index=True)


def _read_raw(path):
    """Read a report file into a header-less string DataFrame. Handles real .xlsx/.xls,
    the NIC 'Export To Excel' HTML-table-saved-as-.xls, and .csv."""
    low = path.lower()
    if low.endswith(".csv"):
        return pd.read_csv(path, dtype=str, header=None, keep_default_na=False)
    # try a genuine spreadsheet first (openpyxl for xlsx, xlrd for old xls)
    try:
        return pd.read_excel(path, dtype=str, header=None)
    except Exception:
        pass
    # NIC reports are frequently an HTML <table> with an .xls name -> read_html
    try:
        tables = pd.read_html(path)
        if tables:
            return _as_headerless(max(tables, key=lambda t: t.shape[0] * t.shape[1]))
    except Exception:
        pass
    # last resort: HTML bytes decoded loosely
    with open(path, "rb") as fh:
        data = fh.read()
    tables = pd.read_html(data.decode("utf-8", "ignore"))
    return _as_headerless(max(tables, key=lambda t: t.shape[0] * t.shape[1]))


def load_export(path) -> pd.DataFrame:
    """Read an EWB export (xlsx/xls/csv or HTML-.xls). Finds the header row even if there
    are title rows (GSTIN / report name / date range) above it."""
    path = str(path)
    raw = _read_raw(path)
    # find header row: the row with the most known keywords
    best_i, best_score = 0, -1
    for i in range(min(15, len(raw))):
        score = sum(any(k in _norm(v) for keys in _FIELDS.values() for k in keys)
                    for v in raw.iloc[i].tolist())
        if score > best_score:
            best_i, best_score = i, score
    df = raw.iloc[best_i + 1:].copy()
    df.columns = [str(x) for x in raw.iloc[best_i].tolist()]
    df = df.dropna(how="all").reset_index(drop=True)
    return normalise(df)


def load_folder_all(folder) -> pd.DataFrame:
    """Combine EVERY e-way bill file in a folder (all 5-day chunks, all years) into one
    de-duplicated table, sorted by date. This is the single consolidated EWB register."""
    from pathlib import Path as _P
    folder = _P(folder)
    if not folder.exists():
        return pd.DataFrame()
    files = []
    for ext in ("*.xlsx", "*.xls", "*.csv"):
        files += list(folder.glob(ext))
    frames = []
    for f in sorted(files):
        try:
            frames.append(load_export(f))
        except Exception:
            continue
    if not frames:
        return pd.DataFrame()
    allrows = pd.concat(frames, ignore_index=True)
    allrows = allrows[allrows["EWB no"].astype(str).str.strip() != ""]
    allrows = allrows.drop_duplicates(subset=["EWB no"]).reset_index(drop=True)
    sort_key = allrows["EWB date"].fillna(allrows["Doc date"])
    allrows = allrows.assign(_k=sort_key).sort_values("_k").drop(columns="_k").reset_index(drop=True)
    return allrows


def consolidated_sheets(alldf: pd.DataFrame) -> dict:
    """Workbook sheets for the single consolidated EWB register: the full line-level
    register first, then the same analysis cuts as a per-year workbook."""
    if alldf is None or alldf.empty:
        return {}
    an, _ = analyse_ewb(alldf)
    sheets = {"All e-way bills": alldf}
    order = ["By month", "By customer", "By document type", "By supply type",
             "By transaction type", "By status", "By HSN", "By transporter"]
    for k in order:
        v = an.get(k)
        if v is not None and not v.empty:
            sheets[k[:31]] = v
    return sheets


def normalise(df: pd.DataFrame) -> pd.DataFrame:
    m = _map_columns(df)
    out = pd.DataFrame()
    out["EWB no"] = df[m["ewb_no"]] if "ewb_no" in m else ""
    out["EWB date"] = _parse_date(df[m["ewb_date"]]) if "ewb_date" in m else pd.NaT
    out["Doc no"] = df[m["doc_no"]] if "doc_no" in m else ""
    out["Doc date"] = _parse_date(df[m["doc_date"]]) if "doc_date" in m else pd.NaT
    out["Doc type"] = (df[m["doc_type"]].map(lambda x: DOC_TYPES.get(str(x).strip().upper(), x))
                       if "doc_type" in m else "")
    out["Supply type"] = df[m["supply_type"]].astype(str).str.title() if "supply_type" in m else ""
    out["Transaction"] = df[m["txn_type"]] if "txn_type" in m else ""
    out["Status"] = df[m["status"]].astype(str).str.title() if "status" in m else "Active"
    out["Party GSTIN"] = df[m["party_gstin"]].astype(str).str.strip().str.upper() if "party_gstin" in m else ""
    out["Party name"] = df[m["party_name"]].astype(str).str.strip() if "party_name" in m else ""
    out["POS / State"] = df[m["place"]] if "place" in m else ""
    out["Taxable value"] = _enum(df[m["value"]]) if "value" in m else 0.0
    for fld, col in (("igst", "IGST"), ("cgst", "CGST"), ("sgst", "SGST"), ("cess", "Cess")):
        out[col] = _enum(df[m[fld]]) if fld in m else 0.0
    out["HSN"] = df[m["hsn"]].astype(str).str.strip() if "hsn" in m else ""
    out["Transporter"] = df[m["transporter"]].astype(str).str.strip() if "transporter" in m else ""
    out["Distance"] = _enum(df[m["distance"]]) if "distance" in m else 0.0
    out["Mode"] = df[m["mode"]] if "mode" in m else ""
    out["Vehicle"] = df[m["vehicle"]] if "vehicle" in m else ""
    out["Total tax"] = out[["IGST", "CGST", "SGST", "Cess"]].sum(axis=1)
    out["Period"] = out["Doc date"].dt.strftime("%Y-%m")
    out.loc[out["Period"].isna() | (out["Period"] == "NaT"), "Period"] = out["EWB date"].dt.strftime("%Y-%m")
    out = out[out["EWB no"].astype(str).str.strip() != ""].reset_index(drop=True)
    return out


def _is_cancelled(s):
    return s.astype(str).str.contains("cancel", case=False, na=False)


def analyse_ewb(df: pd.DataFrame):
    """Returns dict of analysis frames + a summary dict."""
    if df is None or df.empty:
        return {}, {"count": 0, "value": 0.0, "cancelled": 0, "outward": 0.0}
    active = df[~_is_cancelled(df["Status"])]
    money = ["Taxable value", "IGST", "CGST", "SGST", "Cess", "Total tax"]

    def grp(by, extra_sort="Taxable value"):
        g = active.groupby(by, dropna=False)
        agg = g.agg(EWBs=("EWB no", "nunique"), **{c: (c, "sum") for c in money}).reset_index()
        return agg.sort_values(extra_sort, ascending=False).reset_index(drop=True)

    out = {}
    # customer-wise (recipient)
    if (active["Party GSTIN"].astype(str).str.len() > 2).any() or (active["Party name"] != "").any():
        out["By customer"] = grp(["Party GSTIN", "Party name"])
    out["By document type"] = grp(["Doc type"])
    if (active["Supply type"] != "").any():
        out["By supply type"] = grp(["Supply type"])
    if (active["Transaction"].astype(str) != "").any():
        out["By transaction type"] = grp(["Transaction"])
    if (active["HSN"].astype(str).str.len() > 1).any():
        out["By HSN"] = grp(["HSN"]).head(50)
    if (active["Transporter"].astype(str).str.len() > 1).any():
        out["By transporter"] = grp(["Transporter"]).head(50)
    # status (incl. cancelled)
    st = df.groupby(df["Status"].astype(str), dropna=False).agg(
        EWBs=("EWB no", "nunique"), **{"Taxable value": ("Taxable value", "sum")}).reset_index()
    out["By status"] = st.sort_values("EWBs", ascending=False).reset_index(drop=True)
    # month-wise
    out["By month"] = (active.groupby("Period").agg(
        EWBs=("EWB no", "nunique"), **{c: (c, "sum") for c in money}).reset_index().sort_values("Period"))

    summ = {"count": int(df["EWB no"].nunique()), "value": float(active["Taxable value"].sum()),
            "cancelled": int(_is_cancelled(df["Status"]).sum()),
            "outward": float(active.loc[active["Supply type"].str.contains("out", case=False, na=False),
                                        "Taxable value"].sum()) or float(active["Taxable value"].sum()),
            "customers": int(active["Party GSTIN"].replace("", pd.NA).nunique())}
    return out, summ


def monthwise_outward(df: pd.DataFrame) -> pd.DataFrame:
    """For reconciliation vs GSTR-1: month -> EWB taxable value (outward, active only)."""
    if df is None or df.empty:
        return pd.DataFrame(columns=["Period", "EWB taxable value", "EWB tax", "EWBs"])
    active = df[~_is_cancelled(df["Status"])]
    if active["Supply type"].str.contains("out", case=False, na=False).any():
        active = active[active["Supply type"].str.contains("out", case=False, na=False)]
    g = active.groupby("Period").agg(**{"EWB taxable value": ("Taxable value", "sum"),
                                        "EWB tax": ("Total tax", "sum"), "EWBs": ("EWB no", "nunique")}).reset_index()
    return g.sort_values("Period").reset_index(drop=True)


def reconcile_with_gstr1(ewb_month: pd.DataFrame, g1_tot: pd.DataFrame) -> pd.DataFrame:
    """Month-wise EWB outward value vs GSTR-1 taxable value."""
    if ewb_month is None or ewb_month.empty:
        return pd.DataFrame()
    g1 = pd.DataFrame(columns=["Period", "GSTR-1 taxable value"])
    if g1_tot is not None and not g1_tot.empty and "Taxable value" in g1_tot:
        g1 = g1_tot[["Period", "Taxable value"]].rename(columns={"Taxable value": "GSTR-1 taxable value"})
    out = ewb_month[["Period", "EWB taxable value", "EWBs"]].merge(g1, on="Period", how="outer").fillna(0.0)
    out["Difference (EWB - GSTR-1)"] = out["EWB taxable value"] - out["GSTR-1 taxable value"]

    def flag(r):
        d = r["Difference (EWB - GSTR-1)"]
        if r["EWB taxable value"] > 0 and r["GSTR-1 taxable value"] == 0:
            return "EWB but no GSTR-1"
        if abs(d) <= max(10000, 0.05 * max(r["EWB taxable value"], 1)):
            return "OK"
        return "EWB > GSTR-1" if d > 0 else "GSTR-1 > EWB"
    out["Flag"] = out.apply(flag, axis=1)
    return out.sort_values("Period").reset_index(drop=True)


def partywise_outward(df: pd.DataFrame) -> pd.DataFrame:
    """Recipient-GSTIN-wise EWB outward taxable value (active only), for reconciliation
    against GSTR-1 B2B. Returns: Party GSTIN, Party name, EWB taxable value, EWB tax, EWBs."""
    cols = ["Party GSTIN", "Party name", "EWB taxable value", "EWB tax", "EWBs"]
    if df is None or df.empty:
        return pd.DataFrame(columns=cols)
    active = df[~_is_cancelled(df["Status"])]
    if active["Supply type"].str.contains("out", case=False, na=False).any():
        active = active[active["Supply type"].str.contains("out", case=False, na=False)]
    active = active.copy()
    active["Party GSTIN"] = active["Party GSTIN"].astype(str).str.strip().str.upper()
    active = active[active["Party GSTIN"].str.len() >= 15]      # B2B only (registered counterparties)
    if active.empty:
        return pd.DataFrame(columns=cols)
    name = (active.groupby("Party GSTIN")["Party name"]
            .agg(lambda s: next((x for x in s if str(x).strip()), "")))
    g = active.groupby("Party GSTIN").agg(**{"EWB taxable value": ("Taxable value", "sum"),
                                             "EWB tax": ("Total tax", "sum"),
                                             "EWBs": ("EWB no", "nunique")}).reset_index()
    g["Party name"] = g["Party GSTIN"].map(name).fillna("")
    return g[cols].sort_values("EWB taxable value", ascending=False).reset_index(drop=True)


def reconcile_partywise_gstr1(ewb_party: pd.DataFrame, g1_b2b: pd.DataFrame,
                              tol_abs=10000, tol_pct=0.05) -> pd.DataFrame:
    """Party-wise (recipient-GSTIN) EWB outward value vs GSTR-1 B2B taxable value.
    Full outer join so a GSTIN in one source but not the other is surfaced, not hidden."""
    ecols = ["Party GSTIN", "Party name", "EWB taxable value", "EWB tax", "EWBs"]
    if ewb_party is None or ewb_party.empty:
        ewb_party = pd.DataFrame(columns=ecols)
    e = ewb_party.copy()
    e["Party GSTIN"] = e["Party GSTIN"].astype(str).str.strip().str.upper()

    g = pd.DataFrame(columns=["Party GSTIN", "GSTR-1 invoices", "GSTR-1 taxable value", "GSTR-1 tax"])
    if g1_b2b is not None and not g1_b2b.empty:
        gg = g1_b2b.copy()
        gg["Party GSTIN"] = gg["Party GSTIN"].astype(str).str.strip().str.upper()
        gg["GSTR-1 taxable value"] = gg["Taxable value"]
        gg["GSTR-1 tax"] = gg[["IGST", "CGST", "SGST", "Cess"]].sum(axis=1)
        g = gg[["Party GSTIN", "GSTR-1 invoices", "GSTR-1 taxable value", "GSTR-1 tax"]]

    out = e.merge(g, on="Party GSTIN", how="outer")
    # carry a name even for GSTIN-only-in-GSTR-1 rows
    out["Party name"] = out["Party name"].fillna("")
    for c in ("EWB taxable value", "EWB tax", "EWBs", "GSTR-1 invoices",
              "GSTR-1 taxable value", "GSTR-1 tax"):
        out[c] = pd.to_numeric(out.get(c), errors="coerce").fillna(0.0)
    out["Difference (EWB - GSTR-1)"] = out["EWB taxable value"] - out["GSTR-1 taxable value"]

    def flag(r):
        ewb, g1, d = r["EWB taxable value"], r["GSTR-1 taxable value"], r["Difference (EWB - GSTR-1)"]
        if ewb > 0 and g1 == 0:
            return "In EWB, not in GSTR-1"       # possible unreported B2B sale
        if g1 > 0 and ewb == 0:
            return "In GSTR-1, no EWB"            # invoice filed, no e-way bill
        if abs(d) <= max(tol_abs, tol_pct * max(ewb, 1)):
            return "OK"
        return "EWB > GSTR-1" if d > 0 else "GSTR-1 > EWB"

    out["Flag"] = out.apply(flag, axis=1)
    out = out[["Party GSTIN", "Party name", "EWBs", "EWB taxable value", "GSTR-1 invoices",
               "GSTR-1 taxable value", "Difference (EWB - GSTR-1)", "Flag"]]
    # mismatches first, then by size of EWB value
    order = {"In EWB, not in GSTR-1": 0, "EWB > GSTR-1": 1, "GSTR-1 > EWB": 2,
             "In GSTR-1, no EWB": 3, "OK": 4}
    out["_o"] = out["Flag"].map(order).fillna(9)
    out = out.sort_values(["_o", "EWB taxable value"], ascending=[True, False]).drop(columns="_o")
    return out.reset_index(drop=True)


def partywise_summary(recon: pd.DataFrame) -> dict:
    if recon is None or recon.empty:
        return {"parties": 0, "matched": 0, "mismatch": 0, "ewb_only": 0, "gstr1_only": 0,
                "ewb_total": 0.0, "gstr1_total": 0.0}
    f = recon["Flag"]
    return {"parties": int(len(recon)),
            "matched": int((f == "OK").sum()),
            "mismatch": int(f.isin(["EWB > GSTR-1", "GSTR-1 > EWB"]).sum()),
            "ewb_only": int((f == "In EWB, not in GSTR-1").sum()),
            "gstr1_only": int((f == "In GSTR-1, no EWB").sum()),
            "ewb_total": float(recon["EWB taxable value"].sum()),
            "gstr1_total": float(recon["GSTR-1 taxable value"].sum())}
