"""Prompt templates sent to Gemini.

The output structure is defined once in ``REPORT_SECTIONS``; the parser and the
GUI tabs use the same definitions, so headings stay consistent end-to-end.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class SectionDef:
    number: int
    title: str
    guidance: str
    aliases: tuple[str, ...] = ()


